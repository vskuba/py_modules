"""Переиспользование соединений httpx: транспорт — общий, клиент — на вызов.

Для тех мест, где клиент **обязан** быть разовым, а соединения к нему — нет.
Разовый клиент нужен там, где у каждого вызова свои cookie: общий на всех клиент
был бы одним мешком, и вход одной учётки протёк бы в запросы другой. Но вместе с
клиентом каждый раз заводится и его пул: круг по сотне учёток означает сотню
рукопожатий TCP и TLS к одному и тому же хосту.

Развязка — отдать клиенту **чужой транспорт**. Соединения живут в нём и
переиспользуются, а клиент остаётся тем, чем и должен быть: набором настроек
вызова (таймаут, заголовки, cookie), сборка которого стоит микросекунды.

⚠ **Такой клиент не закрывают.** `aclose()` клиента закрывает и транспорт, а он
общий — с ним остались бы без пула все остальные вызовы. Течь тут нечему: своих
сокетов у клиента нет, они все у транспорта.

```python
client = httpx.AsyncClient(timeout=10, cookies=свои, transport=http_pool_transport())
response = await client.get(url)      # закрывать клиента не нужно
```

⚠ **Выход наружу — часть ключа транспорта.** `http_pool_transport(proxy)` отдаёт
свой транспорт под каждый прокси: соединение уже установлено через конкретный
адрес, и переиспользовать его для запроса с другим выходом нельзя — сайт увидел
бы ту же учётку с чужого IP (`http_proxy.py`).

Граница с соседом: `http_heartbeat_client()` решает ту же задачу с другой
стороны — там **один** долгоживущий клиент на все сессии, а cookie передаются
на каждый запрос (`http_heartbeat.md`, §1). Это дешевле и правильнее там, где
такой клиент есть кому держать; здесь — там, где вызовы разбросаны по коду и
держать его некому.
"""

import asyncio
import weakref

import httpx

# Транспорты по циклам событий **и по выходу наружу**. Приложение обычно живёт на
# одном цикле, но фоновая смена или сюита поднимают свой `asyncio.run` —
# транспорт, рождённый на чужом цикле, чужим и останется: пул соединений привязан
# к циклу, и после его конца это «Event loop is closed» в первом же обращении.
#
# ⚠ **Прокси — часть ключа, а не настройка клиента.** Соединение уже установлено
# через конкретный выход, и отдать его запросу с другим прокси нельзя: сайт
# увидел бы учётку с чужого адреса. Один транспорт на выход означает и
# переиспользование соединений внутри выхода, и невозможность их перепутать.
# Записи гаснут вместе с циклом.
_transports: dict[tuple[int, str], httpx.AsyncHTTPTransport] = {}


def http_pool_transport(proxy: str = '') -> httpx.AsyncHTTPTransport:
    """Общий транспорт текущего цикла событий; соединения переиспользует сам httpx.

    Args:
        proxy: адрес прокси (`http_proxy_url`) — тогда транспорт свой у этого
            выхода. Пусто — прямой выход, как было.

    Вызывать только из работающего цикла — он часть ключа. Ограничение пула
    httpx (100 соединений на хост) не трогаем: сколько запросов идёт разом,
    решает вызывающий, и обычно у него для этого свой семафор.

    ⚠ **Пустой прокси и заданный — разные транспорты, и путать их нельзя.** Там,
    где адрес выхода привязан к учётке (сайты считают вход по IP), запрос мимо
    своего прокси выглядит как вход с другого адреса — то есть ровно то, от чего
    прокси и заводился.
    """
    loop = asyncio.get_running_loop()
    key = (id(loop), str(proxy or ''))
    transport = _transports.get(key)

    if transport is None:
        transport = httpx.AsyncHTTPTransport(proxy=proxy or None)
        _transports[key] = transport
        # Умрёт цикл — умрут и его записи: в сюите каждый тест со своим циклом, и
        # без этого словарь рос бы до конца процесса мусором из закрытых пулов.
        weakref.finalize(loop, _transports_drop, id(loop))

    return transport


def _transports_drop(loop_key: int) -> None:
    """Убирает все транспорты умершего цикла — по одному на каждый выход.

    Раньше запись была одна на цикл и снималась `dict.pop`. Теперь их столько,
    сколько прокси успел увидеть цикл, и `pop` по одному ключу оставил бы
    остальные мусором до конца процесса.
    """
    for key in [key for key in _transports if key[0] == loop_key]:
        _transports.pop(key, None)
