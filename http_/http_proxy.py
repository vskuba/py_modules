"""Сетевой прокси: собрать адрес, проверить его, узнать внешний IP.

⚠ **Почему в общем слое, а не в проекте.** Прокси нужен обоим концам одной
работы: RhapsodyAi ведёт через него Chromium, DatingAi через тот же самый
стучится в API сайта, держит присутствие и вебсокет. Разложи мы это по проектам —
получили бы две сборки одного URL и две разные трактовки «прокси не отвечает»,
расходящиеся на первой же правке.

## Зачем это вообще

Сайты знакомств считают учётки **по внешнему адресу**: с одного IP пускают
несколько девушек, дальше вход отвергается. Поэтому анкете нужен свой выход, и
нужен он **во всех дверях сразу** — сайт видит один и тот же аккаунт то из
браузера, то из нашего HTTP, и разные адреса у них выглядят хуже, чем один общий.

## Что здесь есть

* `http_proxy_parse` — разобрать строку провайдера на части;
* `http_proxy_url` — собрать адрес из частей, с экранированием логина и пароля;
* `http_proxy_hide` — тот же адрес без пароля: для журнала и для ответа наружу;
* `http_proxy_check` — сходить через прокси и узнать, **каким адресом нас видят**;
* `http_proxy_direct_ip` — тот же вопрос, но **без прокси**: с какого адреса
  ходит сама машина. Нужен для сравнения: прокси, выходящий нашим же адресом,
  ничего не скрывает — и узнать об этом лучше в реестре, чем от сайта.

⚠ **Разбор строки нужен потому, что каналы покупают пачками.** Провайдер
присылает список — по строке на выход, и формат у каждого свой: кто-то
`socks5://user:pass@host:1080`, кто-то `host:1080:user:pass`. Заводить такое по
пять полей на строку — верный способ ошибиться на двадцатом канале.

⚠ **Проверка отвечает на вопрос «какой у нас выход», а не «жив ли прокси».**
Разница существенная: два разных прокси нередко выходят одним и тем же IP, и
тогда лимит сайта они делят, ничем этого не показывая. Поэтому проверка обязана
возвращать увиденный адрес, а считать занятость нужно **по нему**, а не по строке
подключения.

## ⚠ Две формы одного адреса

`httpx` раскодирует `%40` в пароле, а `websockets` — **нет**: он берёт userinfo
как есть (`urlparse.username` percent-кодировку не трогает) и шлёт её в
`Proxy-Authorization`. Один и тот же адрес поэтому работает в HTTP и получает
407 в сокете — ровно на тех паролях, где есть `@` или `:`, то есть на половине
выданных провайдерами.

Проверено живьём на стенде: с простым паролем сокет проходит, с
`p%40ss%3Aword` — «proxy rejected connection: HTTP 407».

Отсюда две функции вместо одной: `http_proxy_url` даёт экранированную форму (её
ждут httpx, Playwright и реестр), `http_proxy_ws_url` — ту же строку с
раскодированным логином и паролем для `websockets`. Разбор адреса при этом не
страдает: `urlparse` отделяет userinfo по **последнему** `@`, а он в конце.

## SOCKS

`socks5://` httpx умеет только с пакетом `socksio` (`httpx[socks]`). Его
отсутствие — не поломка прокси, а нехватка зависимости, и разговор при этом
разный: в первом случае меняют прокси, во втором ставят пакет. Поэтому случай
разбирается отдельно и называется словами.
"""

import time
from urllib.parse import quote, unquote

import httpx

from logging_.logging_ import logger_info

# Схемы, которые понимает httpx. `socks4` не берём: из живых прокси он почти
# исчез, а лишняя схема в списке — это лишняя ветка в проверке.
HTTP_PROXY_SCHEMES = ('http', 'https', 'socks5', 'socks5h')

# Куда ходим за своим адресом. Отвечает `{"ip": "1.2.3.4", "country": "UA", …}`.
#
# ⚠ **Страну берём там же, где и адрес, а не вторым запросом.** Это то же самое
# знание («откуда нас видят»), и добывать его двумя походами значило бы удвоить
# время проверки на каждый выход — а их проверяют пачками по два десятка.
#
# ⚠ Служба по **HTTPS**: через прокси идёт весь запрос, и по HTTP его содержимое
# видит владелец канала. Здесь секретов нет, но правило дешевле исключения.
#
# ⚠ Адрес задаётся переменной, потому что служба однажды ляжет или начнёт
# требовать ключ, и менять это правкой кода в двух проектах — плохой план.
# Страны в ответе может не оказаться (другая служба) — тогда она просто пуста.
HTTP_PROXY_CHECK_URL = 'https://ipinfo.io/json'

# Проверка должна быть быстрой: её гоняют пачкой по всему реестру. Прокси,
# который думает дольше пятнадцати секунд, для работы всё равно не годится.
HTTP_PROXY_CHECK_TIMEOUT = 15.0


def http_proxy_parse(text: str, scheme: str = 'http') -> dict:
    """Строка провайдера → части: `{scheme, host, port, username, password}`.

    Понимает три записи, которые и встречаются:

    * `socks5://user:pass@host:1080` — с указанием схемы;
    * `host:1080:user:pass` — самая частая у продавцов, схемы в ней нет;
    * `host:1080` — канал без авторизации.

    Args:
        text: строка как её прислал провайдер.
        scheme: чем считать запись без схемы. По умолчанию `http` — так
            выдают большинство; SOCKS в такой записи придётся выбрать руками.

    Returns:
        dict: части адреса. Пароль и логин — **как в строке**, без
        экранирования: экранирует их `http_proxy_url` при сборке.

    Raises:
        ValueError: разобрать не вышло. Текст годится человеку в ответ: он
            вставлял строку и должен понять, чем она не подошла.

    ⚠ **Пароль с `:` и `@` ломает короткую запись, и это не наша беда.** В
    `host:port:user:pass` разделитель — двоеточие, и пароль `p:ss` делает строку
    неоднозначной. Такие каналы заводятся полной записью со схемой, где
    userinfo отделён последним `@`; предупредить об этом дешевле, чем угадывать.
    """
    raw = str(text or '').strip()
    if not raw:
        raise ValueError('пустая строка')

    if '://' in raw:
        got_scheme, rest = raw.split('://', 1)
        scheme = got_scheme.strip().lower()
    else:
        rest = raw

    username = password = ''

    # ⚠ **`@` в строке ещё не значит «полная запись».** В короткой он попадается
    # внутри пароля — `host:1080:user:p@ss` вполне обычная строка от продавца, —
    # и деление по последнему `@` давало из неё хост «ss». Поймано на первом же
    # заведении.
    #
    # Различаем по тому, что стоит **после** последнего `@`: у полной записи там
    # `хост:порт`, то есть двоеточие и цифры. Не сошлось — значит `@` был частью
    # пароля, и запись короткая.
    if '@' in rest and _host_port(rest.rsplit('@', 1)[1]):
        auth, rest = rest.rsplit('@', 1)
        username, _, password = auth.partition(':')
    else:
        # Короткая запись `host:port:user:pass`. Режем по первым двум
        # двоеточиям: остаток целиком — пароль, даже если в нём есть свои.
        parts = rest.split(':')
        if len(parts) >= 4:
            rest = ':'.join(parts[:2])
            username, password = parts[2], ':'.join(parts[3:])
        elif len(parts) == 3:
            raise ValueError('непонятная запись: ожидались «хост:порт» либо '
                             '«хост:порт:логин:пароль»')

    host, _, port = rest.rpartition(':')
    if not host or not port.isdigit():
        raise ValueError('не разобрать хост и порт: ожидалось «хост:порт»')

    if scheme not in HTTP_PROXY_SCHEMES:
        raise ValueError(f'схема не из списка: {scheme}')

    return {'scheme': scheme, 'host': host.strip(), 'port': int(port),
            'username': username, 'password': password}


def http_proxy_url(scheme: str, host: str, port: int,
                   username: str = '', password: str = '') -> str:
    """Адрес прокси одной строкой: `socks5://user:pass@host:1080`.

    Args:
        scheme: `http`, `https`, `socks5` или `socks5h`.
        host: имя или адрес прокси.
        port: порт.
        username: логин; пусто — прокси без пароля.
        password: пароль.

    Returns:
        str: адрес, годный для `httpx(proxy=…)` и для Playwright.

    ⚠ **Логин и пароль экранируются.** У провайдеров прокси в пароле регулярно
    попадаются `@`, `:` и `/`, а именно на них разбирается URL: неэкранированный
    `p@ss` превращает часть пароля в имя хоста, и ошибка выглядит как «прокси не
    отвечает» — искать её будут где угодно, только не в пароле.
    """
    scheme = str(scheme or 'http').strip().lower()
    if scheme not in HTTP_PROXY_SCHEMES:
        raise ValueError(f'схема прокси не из списка: {scheme}')

    auth = ''
    if username:
        auth = quote(str(username), safe='') + \
               (':' + quote(str(password), safe='') if password else '') + '@'

    return f'{scheme}://{auth}{str(host).strip()}:{int(port)}'


def http_proxy_hide(url: str) -> str:
    """Тот же адрес, но без пароля: `socks5://user:•••@host:1080`.

    Для журнала, ответа наружу и страницы. ⚠ Правило простое: **пароль прокси
    выходит из своего хранилища ровно в одну сторону** — в клиент, который через
    него пойдёт. Всё остальное показывает эту строку.
    """
    raw = str(url or '')
    if '@' not in raw or '://' not in raw:
        return raw

    scheme, rest = raw.split('://', 1)
    auth, host = rest.rsplit('@', 1)
    user = auth.split(':', 1)[0]

    return f'{scheme}://{user}:•••@{host}' if ':' in auth else f'{scheme}://{user}@{host}'


def http_proxy_ws_url(url: str) -> str:
    """Тот же адрес, но с раскодированными логином и паролем — для `websockets`.

    ⚠ **Не косметика, а исправление настоящего отказа.** `websockets` шлёт
    userinfo в `Proxy-Authorization` как есть, без раскодирования: пароль
    `p%40ss%3Aword` уезжает к прокси именно этими символами, и тот отвечает 407.
    `httpx` ту же строку раскодирует и проходит — то есть HTTP-двери анкеты
    работают, а чат молчит, и выглядит это как беда сокета, а не пароля.

    Пусто на входе — пусто на выходе: «выхода нет» остаётся «выхода нет».
    """
    raw = str(url or '')
    if '://' not in raw or '@' not in raw:
        return raw

    scheme, rest = raw.split('://', 1)
    auth, host = rest.rsplit('@', 1)
    username, _, password = auth.partition(':')

    auth = unquote(username) + (':' + unquote(password) if password else '')

    return f'{scheme}://{auth}@{host}'


# Свой внешний адрес и когда его узнали. Меняется он редко (у сервера — почти
# никогда), а спрашивать его на каждый показ страницы значит ходить наружу ради
# строки, которая не менялась месяц.
_direct: dict = {'ip': '', 'country': '', 'at': 0.0}

# Сколько живёт этот ответ. Полчаса: смена адреса у сервера — событие, о котором
# узнают и без нас, а держать его вечно нельзя — динамический адрес бывает и у
# машины разработчика.
HTTP_PROXY_DIRECT_FRESH_SEC = 30 * 60


async def http_proxy_direct_ip(force: bool = False) -> dict:
    """С какого адреса машина ходит наружу **без** прокси.

    Args:
        force: спросить заново, не глядя на кэш.

    Returns:
        dict: `ip`, `country` и `ok`. Не дозвонились — `ok: False` и пустой
        адрес; это не беда, а «сейчас не знаем».

    ⚠ **Зачем он вообще.** Прокси, у которого увиденный адрес совпадает с нашим,
    не скрывает ничего: запрос идёт мимо него либо он прозрачный. Для сайта,
    считающего учётки по IP, это худший случай — все анкеты «с прокси» окажутся
    на одном адресе, и узнаем мы об этом из блокировок. Сравнение стоит одного
    похода в полчаса.

    ⚠ **Ничего не бросает** по той же причине, что и `http_proxy_check`: его
    зовут на показ страницы, и отказ службы не должен ронять список выходов.
    """
    if not force and _direct['ip'] and time.monotonic() - _direct['at'] < HTTP_PROXY_DIRECT_FRESH_SEC:
        return {'ip': _direct['ip'], 'country': _direct['country'], 'ok': True}

    got = await http_proxy_check('')
    if got['ok']:
        _direct.update({'ip': got['ip'], 'country': got['country'], 'at': time.monotonic()})

    return {'ip': got['ip'], 'country': got['country'], 'ok': got['ok']}


async def http_proxy_check(url: str = '', check_url: str = HTTP_PROXY_CHECK_URL,
                           timeout: float = HTTP_PROXY_CHECK_TIMEOUT) -> dict:
    """Идёт через прокси наружу и возвращает увиденный адрес.

    Args:
        url: адрес прокси (`http_proxy_url`). **Пусто — идём напрямую**: тем же
            кодом отвечаем на вопрос «а какой адрес у нас самих».
        check_url: куда ходим за своим IP. Ответ ожидается JSON с полем `ip`.
        timeout: предел ожидания, секунды.

    Returns:
        dict: `ok` — прошло ли, `ip` — каким адресом нас видят, `country` — код
        страны по ISO-3166 alpha-2 (`UA`, `DE`), `ms` — сколько занял поход,
        `error` — причина отказа словами (пусто при удаче).

    ⚠ **Ничего не бросает.** Проверку гоняют по всему реестру пачкой, и одна
    мёртвая строка не должна ронять остальные. Отказ — это результат проверки, а
    не происшествие.

    ⚠ **Свой клиент, а не общий транспорт.** Проверка идёт раз в жизни строки и
    должна открывать соединение заново: переиспользованное соединение отвечало бы
    на вопрос «работал ли прокси тогда», а не «работает ли сейчас».
    """
    started = time.monotonic()

    try:
        async with httpx.AsyncClient(proxy=url or None, timeout=timeout,
                                     follow_redirects=False) as client:
            response = await client.get(check_url)
            response.raise_for_status()
            body = response.json()
    except ImportError as e:
        # `socks5://` без пакета `socksio`. Отдельной веткой намеренно: это
        # нехватка зависимости, а не беда прокси, и чинится она установкой
        # `httpx[socks]`, а не сменой адреса.
        return _fail(f'нет поддержки SOCKS: {e}; поставьте httpx[socks]', started)
    except httpx.HTTPError as e:
        # ⚠ Текст у исключения бывает пустым — у `ConnectTimeout` он пуст всегда,
        # и строка выходила как «ConnectTimeout:» с двоеточием в никуда. Имя типа
        # человеку ничего не говорит, поэтому у частых случаев своя фраза.
        return _fail(_why(e), started)
    except ValueError as e:
        # Ответ не разобрался как JSON: обычно это страница-заглушка провайдера
        # или портал «оплатите доступ», отданная вместо нашего запроса.
        return _fail(f'ответ не похож на ожидаемый: {e}'[:200], started)

    ip = str((body or {}).get('ip') or '').strip()
    if not ip:
        return _fail('служба не назвала адрес', started)

    # Код страны — двумя буквами и заглавными: так его пишут в ISO, и так его
    # сравнивают. Нет в ответе — пусто, а не «??»: «не знаем» и «страна такая»
    # это разные вещи, и вторая не должна появляться из умолчания.
    country = str((body or {}).get('country') or '').strip().upper()[:2]

    logger_info(f'[proxy] {http_proxy_hide(url) if url else "прямой выход"} → {ip}'
                + (f' ({country})' if country else ''))

    return {'ok': True, 'ip': ip, 'country': country, 'ms': _ms(started), 'error': ''}


# Отказы, которые случаются чаще прочих, — словами. Остальные показываются
# именем типа: оно хотя бы отличает одно от другого.
HTTP_PROXY_WHY = {
    'ConnectTimeout': 'прокси не ответил вовремя',
    'ConnectError': 'до прокси не достучаться',
    'ProxyError': 'прокси отказал — проверьте логин и пароль',
    'ReadTimeout': 'прокси принял запрос, но не ответил',
    'RemoteProtocolError': 'прокси оборвал соединение',
    'ReadError': 'прокси оборвал чтение на полуслове',
    'WriteError': 'прокси оборвал передачу',
    'ConnectionResetError': 'прокси сбросил соединение',
    'PoolTimeout': 'не дождались свободного соединения',
}


def _host_port(text: str) -> bool:
    """Похоже ли на `хост:порт`. Нужно, чтобы отличить полную запись от короткой."""
    host, _, port = str(text).rpartition(':')

    return bool(host) and port.isdigit()


def _why(error: Exception) -> str:
    """Отказ словами: текст исключения, а нет его — фраза по типу."""
    name = type(error).__name__
    text = str(error).strip()

    if text:
        return f'{HTTP_PROXY_WHY.get(name, name)}: {text}'[:200]

    return HTTP_PROXY_WHY.get(name, name)


def _fail(error: str, started: float) -> dict:
    """Отказ проверки одним видом: та же форма, что и у удачи.

    ⚠ Форма совпадает с удачей **по ключам**, а не только по виду: вызывающий
    кладёт итог в базу одним и тем же кодом, и недостающий ключ обернулся бы
    `KeyError` ровно в тот момент, когда прокси умер.
    """
    return {'ok': False, 'ip': '', 'country': '', 'ms': _ms(started), 'error': error}


def _ms(started: float) -> int:
    return int((time.monotonic() - started) * 1000)
