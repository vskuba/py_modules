# ⚠ Что убрать из названия, прежде чем искать: «м.», «смт», скобки с районом.
# Справочник от этого не растёт, а попаданий заметно больше.
PERSON_UA_POSTCODE_NOISE = re.compile(
    r'^\s*(?:м\.|смт\.?|с\.|сел\.)\s*|\s*\(.*?\)\s*$')


def person_ua_postcode(city: str) -> str:
    """Почтовый индекс города; неизвестный город — пустая строка.

    Args:
        city: название как угодно: «Київ», «м. Київ», «київ», «Київ (центр)».

    Returns:
        Пять цифр строкой либо `''`.

    >>> person_ua_postcode('м. Львів')
    '79000'
    >>> person_ua_postcode("Кам'янець-Подільський")
    '32300'
    >>> person_ua_postcode('Мала Вільшанка')
    ''
    """
    name = PERSON_UA_POSTCODE_NOISE.sub('', str(city or '')).strip().lower()
    name = name.replace('’', "'").replace('ʼ', "'").replace('`', "'")

    return PERSON_UA_POSTCODES.get(name, '')


def _main() -> int:
    parser = argparse.ArgumentParser(
        prog='python -m person_.person_ua_postcode',
        description='Почтовый индекс украинского города.')
    parser.add_argument('city', nargs='+', help='город (можно несколько)')
    args = parser.parse_args()

    for city in args.city:
        print(f'{city}: {person_ua_postcode(city) or "неизвестен"}')

    return 0


