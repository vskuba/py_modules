    parser.add_argument('count', nargs='?', type=int, default=10,
                        help='сколько имён напечатать')
    parser.add_argument('--gender', choices=('m', 'f'), default='',
                        help='только мужские или только женские')
    parser.add_argument('--seed', type=int, default=0,
                        help='повторяемый набор')
    args = parser.parse_args()

    rand = random.Random(args.seed) if args.seed else None
    for _ in range(max(1, args.count)):
        person = person_ua_name(args.gender, rand)
        print(f'{person["first"]} {person["last"]}  ({person["gender"]})')

    return 0


