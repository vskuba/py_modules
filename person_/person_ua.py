# Как мужская форма фамилии становится женской: окончание → окончание.
# ⚠ Порядок важен — длинные окончания проверяются раньше коротких, иначе
# `-цький` поймается правилом `-ий` и даст «Левицька» из «Левицьй».
PERSON_UA_FEMALE_RULES = (
    ('цький', 'цька'), ('ський', 'ська'), ('зький', 'зька'),
    ('ий', 'а'), ('ій', 'я'),
)


def person_ua_name(gender: str = '', rand: random.Random = None) -> dict:
    """Имя, фамилия и род: `{'first': …, 'last': …, 'gender': 'm'|'f'}`.

    Args:
        gender: `'m'`, `'f'` или пусто — тогда род бросается монеткой.
        rand: источник случайности; свой нужен тестам (см. шапку).

    ⚠ Род возвращается третьим полем не для красоты: по нему зовущий решает,
    как обратиться в письме и какое окончание поставить в своей форме. Выводить
    его обратно из имени значило бы заводить второй справочник имён.
    """
    rand = rand or random
    gender = gender if gender in ('m', 'f') else rand.choice(('m', 'f'))
    first = rand.choice(
        PERSON_UA_FIRST_M if gender == 'm' else PERSON_UA_FIRST_F)
    last = rand.choice(PERSON_UA_LAST)

    return {'first': first,
            'last': last if gender == 'm' else person_ua_surname_female(last),
            'gender': gender}


def person_ua_surname_female(last: str) -> str:
    """Женская форма фамилии; несклоняемая по роду возвращается как есть.

    «Коваленко», «Ковальчук», «Мороз» одинаковы у мужчины и женщины — это
    свойство языка, а не недоделка. Меняются только прилагательные формы:
    «Левицький» → «Левицька», «Чорний» → «Чорна».
    """
    clean = str(last or '').strip()
    for male, female in PERSON_UA_FEMALE_RULES:
        if clean.endswith(male):
            return clean[:-len(male)] + female

    return clean


