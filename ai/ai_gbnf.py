"""
GBNF-грамматика для enum-ответа.

Грамматика обязывает модель выдать **ровно одно** из перечисленных значений:
llama.cpp не порождает то, что мимо грамматики, — поэтому ответ шага не надо
ни парсить из JSON, ни переспрашивать, ни уговаривать промптом «ответь ровно
одним словом». Цена мерилась на gx10 small: 2 токена, 0.35–0.6 с на шаг —
против ~4 с того же вопроса через prompt-JSON.

⚠ Грамматика и размышления несовместимы: thinking-блок в грамматику не
влезает, и с включённым thinking модель возвращает пустой `content` (замер
на той же ноде). Гасит thinking тот, кто грамматике знает цену, — провайдер
(`AiProviderGx10.model_get`), а не вызывающий шаг: шаг про провайдер не знает.

Сборка здесь, а не в шаге: грамматика — знание про llama.cpp, а шаг знает
только список ответов.
"""


def ai_gbnf_enum_grammar(values: list | tuple | None) -> str:
    """
    GBNF `root ::= "yes" | "no"` из списка ответов; пустой список — пустая строка.

    Повтор значения молча выбрасывается: в грамматике он всё равно схлопнулся
    бы в одну ветку, а дубль в выводе только сбивает с толку того, кто читает
    метаданные шага. Кавычка и обратный слэш в значении экранируются — иначе
    одно значение с `"` ломало бы всю грамматику.
    """
    words: list[str] = []
    for value in values or []:
        # None — это «чипса пустая», а не значение `"None"`: в ответе его быть не может.
        word = '' if value is None else str(value).strip()
        if word and word not in words:
            words.append(word)

    if not words:
        return ''

    body = ' | '.join(
        '"' + word.replace('\\', '\\\\').replace('"', '\\"') + '"'
        for word in words
    )
    return f'root ::= {body}'
