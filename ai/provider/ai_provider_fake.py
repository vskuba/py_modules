"""Подменная модель: тесты маршрута без единого запроса к живой машине.

## ⚠⚠ Зачем

Тесты, проверяющие **маршрут** workflow, живой модели не требуют: им нужно знать,
каким шагом пошёл поток и что доехало до промпта, — а это решают переходы и
подстановка, а не текст ответа. Плата за живую модель при этом высокая:

* **модель одна на тесты и на прод.** Та же нода, что отвечает `pytest`, отвечает
  живым людям на сайте знакомств; прогон сюиты — отнятые у них ответы;
* **прогон идёт минутами.** Пятнадцать тестов ветвления — пять минут;
* **и он недетерминирован.** Живой прогон уронил проверку ветки «ответ на письмо»
  не поломкой, а решением модели: шаг разбора счёл, что отвечать не нужно, и увёл
  поток на «Тишину». Назавтра то же самое случилось бы с соседним тестом.

Подмена снимает все три: ответ задан заранее, и красное значит «маршрут сломан»,
а не «модель сегодня решила иначе».

## ⚠ Это обычный сервис, а не заглушка в памяти

Адрес и ключ берутся так же, как у любого другого провайдера, — из окружения
(`LLM_FAKE_API_URL`, `LLM_FAKE_API_KEY`), и запрос уходит по HTTP на маленький
OpenAI-совместимый сервер. Так подмена проходит **тот же путь**, что и живая
модель: тот же клиент, те же заголовки, тот же разбор ответа. Заглушка в памяти
этот путь обошла бы — и не заметила бы поломки именно в нём.

## ⚠ Чего она **не** проверяет

Качество текста, работу судьи, осмысленность решений разбора — всё, ради чего
модель и нужна. Это остаётся живому прогону (`LLM_LIVE=1`), и он по-прежнему
единственный способ убедиться, что агент вправду отвечает разумно.
"""
from pydantic_ai.models import Model
from pydantic_ai.models.openai import OpenAIChatModel
from pydantic_ai.providers.openai import OpenAIProvider

from ai.framework.ai_framework_model import AiFrameworkModel
from ai.provider.ai_provider import AiProvider
from config.config import config_get

# Переменная, включающая подмену.
#
# ⚠⚠ Читается **у сервера**, а не у теста: запрос идёт по HTTP, и подмена обязана
# жить там, где собирается модель. На проде переменной нет — значит нет и способа
# включить её снаружи, чем бы ни был запрос.
AI_PROVIDER_FAKE_ENV = 'LLM_FAKE'

# Адрес и ключ подменного сервиса. ⚠ Имена не по общему правилу
# (`FAKE_API_URL`), а с приставкой `LLM_`: в окружении рядом живут переменные
# самых разных служб, и `FAKE_API_URL` не говорит, чей он.
AI_PROVIDER_FAKE_URL_ENV = 'LLM_FAKE_API_URL'
AI_PROVIDER_FAKE_KEY_ENV = 'LLM_FAKE_API_KEY'


class AiProviderFake(AiProvider):
    """Стратегия подменного сервиса: тот же путь, другой адрес."""

    name = 'fake'

    # ⚠ Считается локальной: пинговать подмену незачем, а «жива ли она» тест
    # узнаёт иначе — по ручке режима, и до первого же вызова.
    local = True

    def model_get(self, model_name: str, framework_model: AiFrameworkModel) -> Model:
        provider = OpenAIProvider(
            base_url=config_get(AI_PROVIDER_FAKE_URL_ENV),
            api_key=config_get(AI_PROVIDER_FAKE_KEY_ENV) or 'fake',
            http_client=self.http_client,
        )

        # ⚠ Через общую сборку, а не своим вызовом: запрет размышлений подмена
        # обязана переживать так же, как живой сервис, — иначе тест на запрет
        # проверял бы не то, что поедет на прод.
        return self.model_assemble(OpenAIChatModel, model_name, provider,
                                   framework_model)

    def raw_endpoint(self, model_name: str) -> tuple[str, str]:
        """Адрес и ключ для запроса мимо pydantic-ai — те же, что у сборки."""
        return (config_get(AI_PROVIDER_FAKE_URL_ENV),
                config_get(AI_PROVIDER_FAKE_KEY_ENV) or 'fake')


def ai_provider_fake_on() -> bool:
    """Включена ли подмена у **этого процесса**.

    ⚠ Отдельной функцией, а не проверкой по месту: спрашивают её и сборка модели,
    и ручка режима, которой тесты убеждаются, что сервер поднят как надо.
    Разойдись эти два чтения — тест уверенно проверял бы живую модель, считая,
    что работает с подменой.

    ⚠⚠ Пустого адреса мало, чтобы считать подмену выключенной, и наоборот:
    решает **только** выключатель. Иначе опечатка в `.env.test` тихо вернула бы
    прогон на живую модель — то есть ровно туда, откуда его уводили.
    """
    return str(config_get(AI_PROVIDER_FAKE_ENV, '')).strip().lower() \
        not in ('', '0', 'false', 'no', 'off')
