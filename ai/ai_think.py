"""Хвост размышлений в ответе модели: срезаем на входе, одним правилом.

## ⚠⚠ ЗАЧЕМ: закрывающий тег приходит без открывающего

Рассуждающие модели пишут ход мысли в `<think>…</think>` и только потом ответ.
Обычно движок отделяет это сам и кладёт в `reasoning_content`, а в `content`
оставляет чистый текст. Но когда размышления **обрывают** — по лимиту или потому
что их выключили насовсем, — сервер дописывает свою прощальную фразу и закрывает
тег, а открывающего в выдаче нет вовсе:

    exceeded, let's stop and write the final answer now.</think>

    I was thinking about our last chat…

⚠ У llama.cpp это **не редкий случай, а каждый ответ**. Размышления там гасят
`--reasoning-budget 0`, и ветка «бюджет вышел» срабатывает сразу, до первого
токена: фраза из `--reasoning-budget-message` приезжает всегда. Замерено на
проде — 5601 ответ из 5601, включая все удачные.

## ⚠ Почему «всё до последнего тега», а не пара

Соблазн — регулярка `<think>.*?</think>`. Она требует **пары**, а пары здесь нет,
и потому молча не находит ничего: строка проходит дальше как есть. Так и вышло —
в `_json_str_clean` стояла ровно такая, и разбор JSON спасал только поиск скобки
`{…}`, отбрасывавший мусор заодно. Текстовый ответ спасать было нечем, и в пул
писем лёг черновик, начинающийся с «exceeded, let's stop…».

Поэтому ищем **последний** закрывающий тег и берём всё после него. Нет тега —
текст не трогаем.

⚠ Именно последний, а не первый: модель, размышляя, способна написать `</think>`
внутри рассуждения (например, пересказывая разметку). Возьми мы первый —
отрезали бы ответ по середине чужой цитаты.

## ⚠ Это защита, а не лечение

Правильное место для починки — настройки сервера: пустая
`--reasoning-budget-message` либо формат, при котором движок сам уносит блок в
`reasoning_content`. Но сервер живёт отдельно от кода и переживает его выкладки, а
цена промаха здесь — текст, уходящий живому человеку. Поэтому срезаем у себя, на
границе, где ответ модели впервые становится нашим.
"""

# Закрывающий тег размышлений. Открывающий не нужен: при обрыве его не бывает.
AI_THINK_MARK = '</think>'


def ai_think_strip(text: str) -> str:
    """Ответ модели без хвоста размышлений.

    Args:
        text: то, что вернула модель.

    Returns:
        str: всё после последнего `</think>`, обрезанное по краям. Тега нет —
        тот же текст, только без крайних пробелов.

    ⚠ Не-строку возвращаем пустой строкой, а не роняем вызов: сюда приезжает
    ответ модели, и `None` при обрыве связи — обычный исход.
    """
    if not isinstance(text, str) or not text:
        return ''

    marker = text.rfind(AI_THINK_MARK)

    return (text[marker + len(AI_THINK_MARK):] if marker >= 0 else text).strip()
