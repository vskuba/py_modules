"""Смены суток ↔ расписание Cronicle: одно и то же, сказанное двумя языками.

Человек задаёт расписание **сменами** — «с девяти до шести», лентой на шкале
суток. Cronicle хранит его **перечнем** — `{'hours': [9, 10, …], 'minutes': [0]}`.
Обе записи про одно, и перевод между ними обязан быть один на оба конца:
разойдись чтение с записью, лента показала бы не то, что планировщик исполняет,
и узналось бы это не отказом, а прогоном, случившимся не тогда.

## ⚠⚠ Шаг — час, и он не наш выбор

Cronicle перемножает `hours` и `minutes`: `{'hours': [9, 10], 'minutes': [0, 30]}`
это четыре запуска, а не два. Значит смену «09:30 → 11:00» перечнем не
записать — минуты одни на все часы. Поэтому смены здесь ложатся на **целые
часы**, а минута запуска одна на всё расписание.

Половинчатая смена не отбрасывается, а честно округляется внутрь: час входит в
расписание, **только если его начало попадает в смену**. Причина не в удобстве,
а в том, что запуск случается в начале часа: час 9 при смене «09:30 → 12:00»
выстрелил бы в 09:00, то есть до её начала.

## ⚠ Граница смены — правая открытая

`с 09:00 до 18:00` значит часы 9…17, а не 9…18. Это то же правило, по которому
живут смены анкет (`from <= минута < to`), и второе здесь было бы расхождением
на ровном месте: человек видит одну ленту и ждёт от неё одного поведения.

## ⚠⚠ Пустых смен не бывает — бывает выключенное событие

Пустой `timing` у Cronicle значит **«каждую минуту»**, а не «никогда». Поэтому
пустые смены сюда не доходят: перевести их нечем, и гасить такое надо
выключателем события. Проверка стоит у вызывающего, а здесь — отказ, потому что
молчаливое `{}` означало бы прогон браузера шестьдесят раз в час.
"""

# Минута, в которую случается запуск внутри часа. ⚠ Одна на всё расписание:
# `minutes` у Cronicle перемножаются с `hours`, и вторая минута удвоила бы
# число запусков во всех сменах разом.
CRONICLE_SHIFT_MINUTE = 0

# Сколько минут в сутках и в часе — чтобы не считать в уме по месту.
CRONICLE_SHIFT_DAY = 24 * 60
CRONICLE_SHIFT_HOUR = 60


def cronicle_shift_timing(rows: list, minute: int = CRONICLE_SHIFT_MINUTE) -> dict:
    """Смены → расписание Cronicle.

    Args:
        rows: смены вида `[{'from': '09:00', 'to': '18:00'}, …]`.
        minute: в какую минуту часа запускать.

    Returns:
        dict: `{'hours': [...], 'minutes': [minute]}` — часы по возрастанию,
        без повторов.

    Raises:
        ValueError: смен нет либо ни один час в них не попал. Пустой `timing`
            для Cronicle значит «каждую минуту», и отдать его молча нельзя.

    ⚠ Пересекающиеся смены сливаются сами: часы лежат множеством, и один час
    не станет двумя запусками оттого, что две смены его накрыли.
    """
    hours = set()
    # ⚠ Считаем **разобранные** смены отдельно от часов: «смен не дали» и «смены
    # дали, но ни один час в них не начинается» — разные беды, и человеку с
    # лентой в руках они выглядят по-разному. Один отказ на оба случая отправил
    # бы его искать пропавшую смену, которую он видит на экране.
    said = 0

    for row in rows or []:
        start = _minutes(row.get('from'))
        stop = _minutes(row.get('to'))

        if start is None or stop is None or stop <= start:
            continue

        said += 1

        for hour in range(0, 24):
            if start <= hour * CRONICLE_SHIFT_HOUR < stop:
                hours.add(hour)

    if not hours and said:
        raise ValueError('смена короче часа и не накрывает ни одного его '
                         'начала: запуск случается в начале часа, и такой '
                         'смене достаться нечему — растяните её до целого часа')

    if not hours:
        raise ValueError('смен нет: пустое расписание Cronicle читает как '
                         '«каждую минуту», а не «никогда» — такое событие '
                         'выключают, а не очищают')

    return {'hours': sorted(hours), 'minutes': [int(minute)]}


def cronicle_shift_rows(timing: dict) -> list:
    """Расписание Cronicle → смены для ленты.

    Args:
        timing: `{'hours': [...], 'minutes': [...]}` как его отдаёт Cronicle.

    Returns:
        list: смены `[{'from': '09:00', 'to': '18:00'}, …]`, по возрастанию.
        Пусто — расписание не выражается сменами (см. ⚠ ниже).

    ⚠⚠ Пустой или бесчасовой `timing` отдаётся **пустым списком**, а не сменой
    на целые сутки. У Cronicle это «каждый час» (а при пустом — и каждую
    минуту), и нарисовать такое сменой значило бы показать человеку расписание,
    которого он не задавал, — а следующее сохранение ленты его бы и закрепило.

    ⚠ Соседние часы сливаются в одну смену: 9…17 читается как «09:00 → 18:00»,
    то есть ровно так, как это задавали. Без слияния лента показывала бы девять
    смен там, где человек провёл одну.
    """
    hours = sorted({int(one) for one in (timing or {}).get('hours') or []
                    if str(one).strip().isdigit() and 0 <= int(one) <= 23})

    if not hours:
        return []

    rows = []
    start = previous = hours[0]

    for hour in hours[1:]:
        if hour == previous + 1:
            previous = hour
            continue
        rows.append(_row(start, previous))
        start = previous = hour

    rows.append(_row(start, previous))

    return rows


def cronicle_shift_minute(timing: dict) -> int:
    """В какую минуту часа стоит запуск. Нет перечня — ноль, начало часа."""
    minutes = [int(one) for one in (timing or {}).get('minutes') or []
               if str(one).strip().isdigit() and 0 <= int(one) <= 59]

    return min(minutes) if minutes else CRONICLE_SHIFT_MINUTE


def _row(first: int, last: int) -> dict:
    """Промежуток часов → смена. ⚠ Правая граница — начало часа **после**
    последнего: часы 9…17 это «09:00 → 18:00», граница открытая."""
    return {'from': _text(first * CRONICLE_SHIFT_HOUR),
            'to': _text(min((last + 1) * CRONICLE_SHIFT_HOUR,
                            CRONICLE_SHIFT_DAY))}


def _text(minutes: int) -> str:
    """Минуты суток → `ЧЧ:ММ`. ⚠ `24:00` остаётся собой: это конец суток, а
    `00:00` на правой границе читалось бы как смена нулевой длины."""
    return f'{minutes // 60:02d}:{minutes % 60:02d}'


def _minutes(text) -> int:
    """`ЧЧ:ММ` → минуты суток. Не разобралось — `None`, решает вызывающий."""
    said = str(text or '').strip()

    if ':' not in said:
        return None

    hour, _, minute = said.partition(':')

    if not hour.strip().isdigit() or not minute.strip().isdigit():
        return None

    got = int(hour) * CRONICLE_SHIFT_HOUR + int(minute)

    return got if 0 <= got <= CRONICLE_SHIFT_DAY else None
