import os

from redis import Redis

_conn = None


def redis_conn_get():
    """Подключиться к Redis — один клиент на процесс, адрес из `REDIS_URL`.

    Returns:
        Redis: клиент, заведённый при первом обращении.

    ⚠ Клиент создаётся **без** `decode_responses`, поэтому `get` отдаёт `bytes`.
    Строки из него читают только через `redis_text`: `str()` на байтах даёт
    питоновское представление `b'…'`, и глазами это не ловится.

    ⚠ Клиент лежит в модульной переменной. Импорт длинной формой
    (`py_modules.redis_.redis_`) загрузит модуль второй раз — и клиентов станет два.
    """
    global _conn
    if _conn is None:
        redis_url = os.getenv("REDIS_URL", "redis://redis:6379")
        _conn = Redis.from_url(redis_url)
    return _conn


def redis_text(value, default: str = '') -> str:
    """Строка из Redis. ⚠ **Он отдаёт байты, а не строку.**

    Args:
        value: то, что вернул `get`.
        default: чем заменить пустоту.

    Returns:
        str: значение строкой. `None` и пустота — `default`.

    ⚠⚠ **Зачем понадобилось, и цена ошибки.** Клиент заводится без
    `decode_responses`, то есть `get` возвращает `bytes`. Обычный `str(raw)` на
    байтах даёт **питоновское представление**: `b'eyJhbGci…'` — вместе с буквой
    `b` и кавычками. Строка выглядит почти правильной, и глазами это не ловится.

    В DatingAi так испортился кэш токена к API сайта знакомств: токен клали
    верным, а читали как `b'eyJ…'`, сайт отвечал `401 IDX12709: CanReadToken()
    returned false` — и панель **входила заново на каждый запрос** вместо одного
    входа в 12 часов. Сайт счёл это перебором паролей и закрыл наш адрес на
    неделю. Причину искали в паролях и в кругах, а она была в одной строке чтения.

    ⚠ Сюита этого не поймала и поймать не могла: поддельный Redis в тестах отдаёт
    `str`, как и положено подделке. Отсюда правило: **читать строки из Redis
    только через эту функцию** — тогда и подделка, и живой клиент дают одно.
    """
    if value is None:
        return default

    if isinstance(value, bytes):
        value = value.decode('utf-8', 'replace')

    return str(value) or default
