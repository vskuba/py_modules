"""Запись журнала: синхронная, своим соединением, и никогда не бросает.

## ⚠⚠ Почему синхронная, хотя всё вокруг асинхронное

Логгер зовут откуда угодно: из обработчика запроса, из потока `rq`, из
кронджоба, у которого цикл событий вот-вот закроется. Асинхронная запись «в
фоне» в двух последних случаях **теряется молча** — задача не успевает
выполниться до конца процесса, и ошибка, ради которой журнал заведён, исчезает.

Несколько миллисекунд на ошибке, которая и так случается редко, дешевле
потерянной записи.

## ⚠⚠ Почему своё соединение, а не пул

Пул принадлежит приложению и живёт в его цикле событий; поток `rq` и кронджоб
до него не дотянутся. Поэтому здесь одно соединение `pymysql` на процесс под
замком: пишут из разных потоков, а соединение не потокобезопасно.

⚠ Перед каждой записью соединение пингуется. База рвёт простаивающие по
`wait_timeout`, а журнал молчит сутками: без пинга первая же ночная ошибка ушла
бы в закрытый сокет.

## ⚠⚠ Не бросает ничего, и жалуется только на уровне INFO

Запись ошибки не должна ронять то, что эту ошибку поймало: иначе недоступная
база превращала бы «не отправилось письмо» в «упал процесс».

А жалоба идёт через `logger_info`, а не `logger_exception`, потому что застава
журнала слушает ERROR: жалоба на недоступную базу пошла бы записываться в ту же
недоступную базу, и так по кругу.
"""

import threading

import pymysql

from logging_.logging_ import logger_info
from mysql_.mysql_ import mysql_conn_get

# Замок на запись: пишут из разных потоков, а соединение не потокобезопасно.
_lock = threading.Lock()

# Соединение процесса. Заводится при первой записи, поднимается после обрыва.
_conn: pymysql.Connection | None = None


def journal_sink_write(sql: str, row: tuple, what: str = 'journal') -> bool:
    """Выполнить запрос журнала и зафиксировать. Отказ — `False`, без исключения.

    Args:
        sql: запрос проекта — его таблица и его столбцы. Слой про них не знает
            и знать не должен: универсальна здесь дисциплина записи, а не схема.
        row: значения подстановки.
        what: чей журнал — словом, для строки жалобы.

    Returns:
        `True` — записали; `False` — не вышло, и об этом сказано в `app.log`.

    ⚠ После неудачи соединение забывается: следующая запись заведёт новое.
    Иначе один оборванный сокет хоронил бы журнал до конца процесса.
    """
    with _lock:
        try:
            conn = _connection()
            with conn.cursor() as cursor:
                cursor.execute(sql, row)
            conn.commit()

            return True
        except Exception as e:
            _drop()
            logger_info(f'[{what}] ошибка не записалась в журнал: {e}')

            return False


def journal_sink_close() -> None:
    """Закрыть соединение журнала. Нужно разовым скриптам и тестам.

    ⚠ Приложению звать не надо: соединение живёт столько же, сколько процесс, и
    закрывать его на остановке незачем — он всё равно кончается.
    """
    with _lock:
        _drop()


def _connection() -> pymysql.Connection:
    """Живое соединение: заводит при первом обращении, поднимает после обрыва.

    ⚠ Зовётся только под замком.
    """
    global _conn

    if _conn is None:
        _conn = mysql_conn_get()
    else:
        _conn.ping(reconnect=True)

    return _conn


def _drop() -> None:
    """Забыть соединение после неудачи. ⚠ Зовётся только под замком."""
    global _conn

    if _conn is not None:
        try:
            _conn.close()
        except Exception:
            pass

        _conn = None
