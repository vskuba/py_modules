"""Отпечаток ошибки: стабильный ключ из меняющегося текста.

Сломавшийся цикл даёт одну и ту же ошибку каждую секунду. Строка на каждую —
десятки тысяч одинаковых записей за ночь и таблица, в которой ничего не найти.
Поэтому строка одна на отпечаток, а повторы считаются счётчиком.

## ⚠⚠ Зачем вычёркивать меняющиеся куски

Текст ошибки почти никогда не повторяется дословно: в нём номер задачи, uuid
сессии, адрес объекта в памяти. Считай отпечаток по тексту как есть — и «задача
5219 не найдена» с «задача 5220 не найдена» станут разными ошибками, а счётчик
повторов потеряет смысл: вместо одной строки журнал скопит по строке на задачу.

Поэтому из текста вычёркиваются uuid, адреса (`0x7f…`) и числа от трёх знаков.
Два знака оставлены намеренно: «код 42» и «код 43» — чаще всего правда разные
ошибки, а «задача 5219» и «задача 5220» — одна.

## ⚠ Только первая строка

Логгер часто получает текст вместе с приклеенной трассировкой, и её адреса
развели бы одинаковые ошибки по разным строкам. Берём первую строку: она и есть
то, что человек читает в списке.
"""

import hashlib
import re

# Длина текста, участвующего в отпечатке. Та же, что обычно хранит столбец
# сообщения: считать отпечаток по тому, чего в базе не окажется, незачем.
JOURNAL_KEY_MESSAGE_MAX = 2000

# Что вычёркиваем: меняющиеся куски — см. ⚠⚠ в заголовке.
JOURNAL_KEY_VARIABLE = (
    # uuid целиком
    re.compile(r'\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b',
               re.I),
    # адреса в памяти (`at 0x7f…`)
    re.compile(r'\b0x[0-9a-f]+\b', re.I),
    # числа от трёх знаков: id, порты, миллисекунды
    re.compile(r'\b\d{3,}\b'),
)


def journal_key(*parts: str, message: str = '') -> str:
    """Отпечаток «той же самой ошибки» — по нему повтор находит свою строку.

    Args:
        parts: что отличает ошибки помимо текста: процесс, имя логгера, сайт.
            Берутся как есть, без вычёркивания: это ключи, а не проза.
        message: текст ошибки. Из него вычёркиваются меняющиеся куски, и
            берётся только первая строка.

    Returns:
        32 шестнадцатеричных знака (md5).

    ⚠ `md5` здесь не про стойкость: отпечаток не подписывает и не скрывает,
    он только сводит одинаковое к одному ключу. Выбран за длину — 32 знака
    влезают в короткий индексируемый столбец.
    """
    head = str(message or '').strip().split('\n', 1)[0]
    for pattern in JOURNAL_KEY_VARIABLE:
        head = pattern.sub('#', head)

    raw = '|'.join([*(str(one or '') for one in parts),
                    head[:JOURNAL_KEY_MESSAGE_MAX]])

    return hashlib.md5(raw.encode('utf-8', errors='ignore')).hexdigest()
