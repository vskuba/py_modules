"""Годен ли выход **для браузера**: открыть им страницу и честно ответить.

## ⚠⚠ Бесплатный выход умирает БЫСТРЕЕ, чем длится прогон

Замерено: отбор нашёл годный адрес, через сорок секунд браузер пошёл им на ту
же страницу — и получил `ERR_TIMED_OUT`. Повторный замер объяснил почему: из
двадцати «анонимных» адресов страницу открыл **один**, и живут они минутами.
Проверка, сделанная заранее, к моменту работы успевает устареть.

Отсюда главное свойство этого модуля: проверка **оставляет сессию живой**
(`keep=True`) и отдаёт её номер. Сценарий продолжает в ней же — между «адрес
работает» и «работаем адресом» не остаётся промежутка, в который он успел бы
умереть.

**Проверять надо тем, чем потом пойдёшь, и не отпуская.** Браузер к тому же
делает не то, что HTTP-клиент: держит CONNECT-туннель и тянет десятки ресурсов
страницы параллельными соединениями, и выход, справляющийся с одним запросом,
на двадцати умирает.

## ⚠ Цена проверки

Браузерная проверка дороже HTTP во много раз: контейнер заводит контекст,
Chromium тянет страницу целиком. Поэтому её не гоняют по всему реестру —
сперва HTTP отсекает заведомо мёртвых (их большинство), и только выжившие
проверяются по-настоящему.

## ⚠⚠ У оставленной сессии обязан быть хозяин

Сессия закрывается при любом исходе — кроме удачи с `keep=True`, где её номер
уходит наружу. Брошенная сессия это вкладка Chromium до перезапуска
контейнера: через сотню адресов браузер станет медленным, и причину будут
искать где угодно, только не в проверке выходов.

Поэтому `keep=True` — договор: взял номер, обязан закрыть
(`browser_session_close`), чем бы работа ни кончилась.
"""

import asyncio
import time

from browser_.browser_upstream import browser_upstream_request
from logging_.logging_ import logger_info

# Сколько ждём страницу.
#
# ⚠⚠ Двадцать секунд, а не сорок пять. Замер: живой выход открывает страницу
# товара за 4–5 секунд, и всё, что тянется дольше двадцати, на практике
# оказывается мёртвым. Сорок пять стоили вчетверо больше времени на каждого
# мертвеца — а их большинство, и пока перебор ползёт, живые успевают умереть.
#
# ⚠ Это проверка, а не работа: сценарию потом даётся свой запас
# (`ORDERS_RUN_STEP_MS`), и он больше.
BROWSER_PROXY_TIMEOUT_MS = 20000

# Чего дожидаемся. ⚠ `domcontentloaded`, а не `load`: ждать последнюю картинку
# значит отвергать выходы, на которых страница отлично работает. Сценарий
# дальше всё равно ждёт свои элементы явно.
BROWSER_PROXY_WAIT = 'domcontentloaded'

# Сколько адресов проверяем разом. ⚠ Потолок не ради вежливости: каждая
# проверка — живая вкладка Chromium в контейнере, и два десятка разом съедают
# его память. Контейнер к тому же общий с соседями.
BROWSER_PROXY_PARALLEL = 4


async def browser_proxy_reach(proxy: str, target: str,
                              timeout_ms: int = BROWSER_PROXY_TIMEOUT_MS,
                              keep: bool = False,
                              agent: dict | None = None) -> dict:
    """Откроет ли БРАУЗЕР эту страницу через этот выход.

    Args:
        proxy: адрес выхода (`http_proxy_url`). Пусто — проверка без прокси:
            тем же кодом отвечаем на вопрос «а открывается ли это вообще».
        target: что открываем — та самая страница, с которой предстоит
            работать, а не главная сайта.
        timeout_ms: сколько ждём страницу.
        keep: оставить сессию живой при удаче и вернуть её номер. ⚠⚠ Для
            работы это единственный верный путь: бесплатный выход умирает за
            минуты, и сессия, открытая проверкой, — доказательство, что он жив
            **сейчас**. Закрыв её, мы через полминуты снова ничего не знаем.
        agent: отпечаток сессии — поля открытия как есть (`user_agent`,
            `extra_headers`, `viewport`, `locale`, `timezone_id`). ⚠⚠ Задаётся
            ТОЛЬКО здесь: это свойства контекста, и у открытой сессии
            Playwright менять их не умеет (`browser_scenario_run._session_take`).
            Кто открыл сессию, тот и назвал отпечаток — другого места нет.

    Returns:
        dict: `ok` — открылась ли, `ms` — сколько занял поход, `error` —
        причина словами (пусто при удаче), `session_id` — номер живой сессии
        при `keep=True` и удаче, иначе пусто.

    ⚠⚠ Проверяем ТОЙ ЖЕ ссылкой, по которой пойдёт сценарий. Главная сайта
    легче внутренней страницы, и выход, справившийся с ней, на карточке товара
    падает по таймауту — проверено живьём.

    ⚠ **Ничего не бросает.** Проверку гоняют по списку, и одна мёртвая строка
    не должна ронять остальные: отказ — это результат проверки, а не
    происшествие. Тот же договор, что у `http_proxy_check`.

    ⚠ Сессия закрывается при любом исходе, **кроме** удачи с `keep=True`:
    брошенная держит вкладку Chromium до перезапуска контейнера. У оставленной
    обязан быть хозяин, который её закроет.
    """
    started = time.monotonic()
    session_id, held = '', False

    try:
        # ⚠ Пустой выход уходит пустой СТРОКОЙ, а не `None`: схема контейнера
        # ждёт строку, и `None` она отвергает 422 «Input should be a valid
        # string» — то есть обещанная выше проверка без прокси не работала.
        #
        # ⚠⚠ Отпечаток раскладывается ЗДЕСЬ, при открытии. Было место, где
        # сессию открывали одним выходом, а отпечаток передавали следующим
        # походом, шагам сценария, — и он молча не применялся: площадка видела
        # `HeadlessChrome/151` вместо собранного «Safari 18.6 · iPhone».
        made = await browser_upstream_request(
            'POST', '/browser/session', {'proxy': proxy, **(agent or {})})
        session_id = str((made.get('session') or {}).get('session_id') or '')
        if not session_id:
            return _fail('контейнер не завёл сессию', started)

        await browser_upstream_request(
            'POST', f'/browser/session/{session_id}/goto',
            {'url': target, 'wait_until': BROWSER_PROXY_WAIT,
             'timeout_ms': int(timeout_ms)})
        held = bool(keep)
    except Exception as error:  # noqa: BLE001 — причина возвращается словами
        return _fail(_why(error), started)
    finally:
        # ⚠ Закрываем всё, что не отдаём наружу: и отказавшую сессию, и
        # удачную, если её номер никому не нужен.
        if session_id and not held:
            await _close(session_id)

    return {'ok': True, 'ms': _ms(started), 'error': '',
            'session_id': session_id if keep else ''}


async def browser_proxy_pick(proxies: list, target: str,
                             limit: int = BROWSER_PROXY_PARALLEL,
                             keep: bool = False,
                             agent: dict | None = None) -> dict:
    """Первый выход из списка, которым браузер **правда** открыл страницу.

    Args:
        proxies: адреса выходов по порядку предпочтения.
        target: страница, которую открываем.
        limit: сколько проверок идут разом.
        keep: оставить живой сессию победителя и вернуть её номер — чтобы
            работа пошла в ней же, без промежутка, в который выход успел бы
            умереть. ⚠ Взял номер — обязан закрыть.
        agent: отпечаток сессий проверки (см. `browser_proxy_reach`). ⚠ Нужен
            именно при `keep=True`: сессия победителя уезжает в работу, и
            отпечаток ей после открытия уже не задать.

    Returns:
        dict: `proxy` — годный адрес (пусто, если ни один не подошёл), `ms` —
        сколько он занял, `tried` — сколько проверили, `errors` — пары
        «адрес → причина» у не подошедших, `session_id` — живая сессия
        победителя при `keep=True`.

    ⚠⚠ Порядок списка сохраняется: берём первый годный, а не того, кто
    ответил быстрее. Список приходит уже упорядоченным (свежесть проверки,
    вердикт анонимности), и переупорядочивать его по скорости одного похода
    значит выбросить знание, которое собиралось кругом проверки.

    ⚠ Проверки идут пачками по `limit`: каждая — живая вкладка Chromium, и
    двадцать разом съедают память контейнера, который к тому же общий с
    соседями.

    ⚠ Пачка доводится до конца, даже если годный нашёлся в её начале: отменять
    уже открытые сессии дороже, чем дождаться их закрытия, и брошенная на
    полпути проверка оставляет вкладку.
    """
    rows = [str(one) for one in (proxies or []) if one]
    errors, tried = {}, 0

    for at in range(0, len(rows), max(1, int(limit))):
        batch = rows[at:at + max(1, int(limit))]
        checks = await asyncio.gather(*(
            browser_proxy_reach(one, target, keep=keep, agent=agent)
            for one in batch))
        tried += len(batch)

        winner = None
        for one, got in zip(batch, checks):
            if not got['ok']:
                errors[one] = got['error']
                logger_info(f'[browser] выход {one} не открыл {target}: '
                            f'{got["error"]}')
                continue
            # ⚠⚠ Победитель один, и это ПЕРВЫЙ годный по порядку списка.
            # Остальные удачные сессии этой пачки закрываем: они уже открыты
            # (пачка шла разом), и бросить их значило бы оставить вкладки
            # Chromium висеть до перезапуска контейнера.
            if winner is None:
                winner = (one, got)
            elif got['session_id']:
                await _close(got['session_id'])

        if winner:
            one, got = winner
            return {'proxy': one, 'ms': got['ms'], 'tried': tried,
                    'errors': errors, 'session_id': got['session_id']}

    return {'proxy': '', 'ms': 0, 'tried': tried, 'errors': errors,
            'session_id': ''}


# ── детали реализации ──────────────────────────────────────────────────────

async def _close(session_id: str) -> None:
    """Закрыть сессию, не уронив проверку её отказом.

    ⚠ Закрытие молчит о своих бедах намеренно: сессия могла уже умереть вместе
    с контейнером, и говорить об этом вызывающему, который спрашивал про
    прокси, значит подменить ответ.
    """
    try:
        await browser_upstream_request(
            'DELETE', f'/browser/session/{session_id}', None)
    except Exception:  # noqa: BLE001 — см. докстринг
        pass


def _why(error: Exception) -> str:
    """Причина отказа словами, без простыни стека Playwright.

    ⚠ Текст режется: `Page.goto` приносит call log на двадцать строк, а в
    журнале и в ответе человеку нужна суть — «не дошли» и чем именно.
    """
    text = str(error).strip().split('\n')[0]

    return (text or type(error).__name__)[:200]


def _fail(error: str, started: float) -> dict:
    return {'ok': False, 'ms': _ms(started), 'error': error, 'session_id': ''}


def _ms(started: float) -> int:
    return int((time.monotonic() - started) * 1000)
