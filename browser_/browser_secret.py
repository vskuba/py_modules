"""Шифрование значений, которые опасно держать в базе открытым текстом.

**Почему шифрование, а не хэш.** Хэш — односторонняя функция, из него исходное
значение не достаётся в принципе; он отвечает на вопрос «это то же самое значение?»
(так проверяют пароль при входе), но не на вопрос «какое значение там было». Пароль от
чужого сайта нужен нам целиком: его подставляют в поле формы и показывают человеку в
кабинете. Значит нужно обратимое преобразование — шифрование с ключом.

**От чего защищает.** Ключ живёт в окружении (`.env`), а не в базе, и вместе с ней не
уезжает. Дамп базы, файл бэкапа, открытая веб-консоль СУБД, SQL-инъекция, украденный
том с данными — всё это отдаёт нападающему шифротекст, из которого без ключа ничего не
следует. Именно этот случай здесь и закрывается: полные бэкапы базы снимаются
регулярно, и без шифрования пароль от чужого сайта лёг бы в каждый из них открытым
текстом.

**От чего не защищает, и это важно понимать.** Приложение обязано уметь расшифровывать
— иначе значение не подставить в форму. Значит любой, кто получил и код на сервере, и
`.env`, получает и значения. Точно так же шифрование ничего не даёт против того, у
кого есть доступ к самому кабинету: там значение показывается сырым, за тем его и
хранят. Шифрование разделяет две разные вещи — «добрался до базы» и «добрался до
приложения», — и делает первое бесполезным без второго.

**Формат.** `enc:v1:<шифротекст>`. Префикс нужен, чтобы отличать зашифрованное от
обычного: в одной колонке лежат и открытые значения (адрес стенда, логин, номер
версии), и закрытые. Без метки пришлось бы гадать по виду строки. Номер версии —
чтобы смена алгоритма не потребовала гадать, чем зашифрована старая запись.

Fernet (AES-128-CBC + HMAC-SHA256) взят из `cryptography`: он проверяет подпись при
расшифровке и не даёт молча получить мусор из подменённой строки. Свой велосипед на
AES здесь был бы ровно тем местом, где ошибаются.
"""

import os

from logging_.logging_ import logger_info

# Переменная окружения с ключом. Ключ — 32 байта в base64, как их выдаёт
# `Fernet.generate_key()`; в репозитории его нет и быть не может, в `.env.dist`
# лежит пустое значение с пояснением, на прод он едет секретом CI.
BROWSER_SECRET_ENV_KEY = 'BROWSER_SECRET_KEY'

# Метка зашифрованного значения. Версия в префиксе: сменится алгоритм — сменится
# `v2`, и старые записи останутся читаемыми, пока их не перепишут.
BROWSER_SECRET_PREFIX = 'enc:v1:'

# Что показываем вместо значения, если ключа нет или он не тот. Молча отдать пустую
# строку нельзя: человек решил бы, что переменная не заполнена, и завёл бы её заново
# поверх целой записи.
BROWSER_SECRET_UNREADABLE = '<не расшифровать: проверьте BROWSER_SECRET_KEY>'


def browser_secret_ready() -> bool:
    """Есть ли рабочий ключ. По нему страница решает, можно ли заводить секреты."""
    return _fernet() is not None


def browser_secret_is_encrypted(value: str) -> bool:
    """Значение уже зашифровано — по метке, а не по виду строки."""
    return str(value or '').startswith(BROWSER_SECRET_PREFIX)


def browser_secret_encrypt(value: str) -> str:
    """
    Зашифровать значение. Returns: `enc:v1:<шифротекст>`.

    Raises:
        RuntimeError: ключа нет. Именно исключение, а не тихое сохранение открытым
            текстом: человек пометил значение секретным и вправе считать, что оно
            секретным и легло. Молчаливая подмена поведения здесь — худший исход из
            возможных, потому что обнаружится она при утечке.

    Уже зашифрованное не шифруем повторно: правка соседнего поля строки не должна
    наматывать слои — расшифровать такое смог бы только столько же раз подряд.
    """
    value = str(value or '')
    if browser_secret_is_encrypted(value):
        return value

    fernet = _fernet()
    if fernet is None:
        raise RuntimeError(
            f'{BROWSER_SECRET_ENV_KEY} не задан — секретное значение сохранять некуда')

    return BROWSER_SECRET_PREFIX + fernet.encrypt(value.encode()).decode()


def browser_secret_decrypt(value: str) -> str:
    """
    Расшифровать значение. Не помечено меткой — вернуть как есть.

    Не помечено — значит лежало открытым: обычная переменная либо запись, заведённая
    до появления шифрования. Такое возвращаем без изменений, иначе страница перестала
    бы показывать всё, что было заведено раньше.

    Сбой расшифровки не роняет запрос: испорченная или чужая строка — это одна
    переменная, а список рисуется целиком. Вместо значения уходит `BROWSER_SECRET_
    UNREADABLE`, и человек видит, что запись есть, но ключ к ней не подходит.
    """
    value = str(value or '')
    if not browser_secret_is_encrypted(value):
        return value

    fernet = _fernet()
    if fernet is None:
        return BROWSER_SECRET_UNREADABLE

    try:
        return fernet.decrypt(value[len(BROWSER_SECRET_PREFIX):].encode()).decode()
    except Exception as error:
        logger_info(f'browser_secret: значение не расшифровано: {type(error).__name__}: {error}')

        return BROWSER_SECRET_UNREADABLE


def _fernet():
    """
    Шифровальщик по ключу из окружения, либо `None`, если ключа нет или он негоден.

    Не кэшируем: `Fernet` дёшев в создании, а кэш пережил бы правку `.env` и заставлял
    бы перезапускать процесс ради смены ключа. Читаем окружение каждый раз, чтобы
    ключ, доставленный деплоем, подхватился рестартом контейнера и только им.

    Импорт внутри функции: библиотека нужна лишь тем, кто работает с секретами, а
    модуль читают и в тестах схемы, где её присутствие не обязано быть условием.
    """
    key = str(os.getenv(BROWSER_SECRET_ENV_KEY) or '').strip()
    if not key:
        return None

    try:
        from cryptography.fernet import Fernet

        return Fernet(key.encode())
    except Exception as error:
        logger_info(f'browser_secret: ключ {BROWSER_SECRET_ENV_KEY} не годится: '
                    f'{type(error).__name__}: {error}')

        return None
