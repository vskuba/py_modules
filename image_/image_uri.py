"""Картинка как строка `data:` — туда и обратно, одним местом на весь слой.

Браузерный контейнер отдаёт кадры строками `data:image/jpeg;base64,…`: по
HTTP байты не положишь, а картинку вернуть надо. Каждый, кто с ними работает,
писал собственные две строки на кодирование и разбор — и они разошлись.

```python
from image_.image_uri import image_uri_make, image_uri_bytes

uri = image_uri_make(shot)             # байты → 'data:image/jpeg;base64,…'
raw = image_uri_bytes(uri)             # и обратно; не разобралось — b''
```

## ⚠⚠ Разбор прощает строку без заголовка

Та же картинка приходит и как `data:image/jpeg;base64,…`, и голым base64 —
зависит от версии контейнера. Берётся хвост после запятой: в первом случае
это тело, во втором запятой нет вовсе и хвост равен всей строке.

## ⚠ Пустые байты вместо исключения

Кадр — свидетельство о работе, а не сама работа. Битая строка не должна
ронять прогон, ради которого кадр и снимался: зовущий получает `b''` и сам
решает, беда это или просто нечего показать.
"""

import base64

# Заголовок строки `data:` для JPEG — им отдают кадры и контейнер, и панель.
#
# ⚠ Тип зашит, а не угадывается: кадры в слое всегда JPEG (`browser_capture`,
# `browser_thumb`, плёнка прогона). Понадобится другой — это параметр, а не
# разбор содержимого.
IMAGE_URI_JPEG = 'data:image/jpeg;base64,'


def image_uri_make(raw: bytes, head: str = IMAGE_URI_JPEG) -> str:
    """Байты картинки строкой `data:`; пустые байты — пустая строка.

    Args:
        raw: содержимое картинки.
        head: заголовок строки; по умолчанию JPEG.

    ⚠ Пустые байты дают пустую строку, а не заголовок без тела: `data:…;base64,`
    браузер покажет сломанной картинкой, и отличить это от «кадра нет» будет
    нечем.
    """
    return f'{head}{base64.b64encode(raw).decode()}' if raw else ''


def image_uri_bytes(uri: str) -> bytes:
    """Картинка из строки `data:` байтами; не разобралось — пусто.

    Принимает и строку с заголовком, и голый base64 (см. шапку модуля).

    ⚠ Не бросает: битый кадр не повод ронять работу, ради которой он снят.

    >>> image_uri_bytes('')
    b''
    """
    text = str(uri or '')
    if not text:
        return b''

    try:
        return base64.b64decode(text.split(',', 1)[-1])
    except Exception:  # noqa: BLE001 — кадр не стоит прогона
        return b''
