"""Плёнка из кадров: что изменилось между ними и GIF по порядку.

Сценарий в браузере делает десятки шагов, и половина из них ничего на экране
не меняет — паузы, чтения, вычисления. Снимок после каждого даёт ленту, где
одинаковые кадры идут подряд пачками: смотреть её бесполезно, хранить дорого.

Модуль отвечает на два вопроса: **«изменилось ли что-нибудь»** и **«собери из
этого плёнку»**. Вместе они дают запись работы, где каждый кадр — настоящее
изменение, а не отсчёт времени.

```python
from image_.image_film import image_film_same, image_film_gif

if not image_film_same(previous, shot):      # что-то поменялось
    film.append(shot)

image_film_gif(film, 'run.gif', ms=900)
```

## ⚠⚠ Сравнение перцептивное, а не побайтовое

Два снимка неподвижной страницы **не равны по байтам**: JPEG пересобирается
каждый раз, а в кадр попадают мигающий курсор, подгруженный шрифт, сдвиг
анимации на пиксель. Побайтовое сравнение объявит изменением каждый кадр, и
плёнка перестанет отличаться от ленты «снимай всё подряд».

Здесь сравниваются **dHash** уменьшенных кадров: знак перепада яркости между
соседними точками. Он не замечает общего осветления и шума сжатия, но ловит
любую перерисовку — появившийся блок, заполненное поле, раскрытый шаг.

## ⚠ Порог — в битах, и он не «чем меньше, тем лучше»

`IMAGE_FILM_TOLERANCE` — сколько битов хеша могут разойтись у кадров, которые
мы считаем одинаковыми. Ноль ловил бы дрожание шрифтов; большое значение
съедало бы настоящие изменения вроде одной заполненной строки.

## ⚠⚠ Pillow, а не OpenCV

`image_unique` считает те же хеши точнее и тремя способами, но тянет `cv2` —
десятки мегабайт в образ ради одного вопроса «одинаковы ли два кадра».
Здесь хватает Pillow, который в слое и так есть.
"""

import argparse
import io
import pathlib
import sys

# Сторона уменьшенного кадра для хеша. ⚠ Восемь на девять: dHash сравнивает
# соседей по горизонтали, и ему нужен лишний столбец.
IMAGE_FILM_SIDE = 8

# Сколько битов хеша могут разойтись у «одинаковых» кадров. См. шапку.
IMAGE_FILM_TOLERANCE = 2

# Сколько миллисекунд держать кадр в GIF по умолчанию.
#
# ⚠ Почти секунда, а не кинематографические 40 мс: это не кино, а разбор —
# каждый кадр читают, а не смотрят. Быстрее человек не успевает понять, что
# изменилось.
IMAGE_FILM_FRAME_MS = 900

# Сколько держать ПОСЛЕДНИЙ кадр. ⚠ Дольше прочих: на нём итог работы, и без
# паузы GIF возвращается к началу ровно в тот момент, когда на него посмотрели.
IMAGE_FILM_LAST_MS = 2500

# Ширина кадра в плёнке. ⚠⚠ Не исходная: кадр страницы — 1280 точек и сотня
# килобайт, а GIF из сорока таких весит десятки мегабайт и не открывается
# вовсе. Шестьсот точек читаются на экране и весят вдесятеро меньше.
IMAGE_FILM_WIDTH = 600

# Потолок высоты кадра в плёнке.
#
# ⚠⚠ Ноль — НЕ РЕЗАТЬ ВОВСЕ, и это умолчание. Обрезка по высоте дважды
# казалась разумной («длинная страница нечитаема») и дважды оказывалась
# неверной: плёнку смотрят, чтобы разобрать работу, а обрезанный кадр
# отвечает на половину вопроса — формы видно, кнопок и итогов нет.
#
# ⚠ Читаемость чинится шириной, а не ножницами: кадр ужимается целиком, и
# пропорции страницы сохраняются.
IMAGE_FILM_HEIGHT = 0

# Сколько цветов держать в палитре кадра.
#
# ⚠⚠ Сто двадцать восемь, а не полные 256: замер на живой плёнке (9 кадров
# страницы магазина) дал 878 КБ против 3505 — вчетверо легче при неотличимой
# на глаз картинке. Страница это текст, рамки и пара фотографий; двух сотен
# оттенков ей не нужно, а GIF платит за каждый размером всего файла.
#
# ⚠ Ниже опускать смысла нет: 64 цвета дали те же 872 КБ — экономия кончается,
# а фотографии товара начинают полосить.
IMAGE_FILM_COLORS = 128

# Заставка первым кадром: по ней видно, где плёнка начинается.
#
# ⚠⚠ Без неё зациклённый GIF читается неверно. Кадры идут по кругу, и человек
# почти всегда попадает в середину: он видит заполненную форму и считает её
# началом работы, а первые шаги принимает за продолжение. Тёмный кадр с одним
# словом разрывает круг — место старта видно, не вглядываясь.
IMAGE_FILM_TITLE = 'Старт…'

# Заставка латиницей — для систем, где кириллического шрифта нет вовсе
# (`font_pick` вернёт встроенный, а он знает только латиницу). ⚠ Лучше, чем
# ряд пустых прямоугольников: те выглядят поломкой, а не подписью.
IMAGE_FILM_TITLE_LATIN = 'Start...'

# Сколько держать заставку. ⚠ Дольше обычного кадра: её читают, а не
# просматривают, и мелькнувшая за 900 мс надпись роли не играет.
IMAGE_FILM_TITLE_MS = 1500

# Ниже этой отметки надпись заставки не опускается, даже если кадр длиннее.
#
# ⚠⚠ Кадр полной страницы бывает в две-три тысячи точек, и «по центру» на нём
# — это тысяча двести сверху. В списке плёнки показывают превью, обрезанное
# по верху: надпись в геометрическом центре в него не попадает вовсе, и
# заставка выглядит пустой тёмной плиткой. Короткий кадр по-прежнему получает
# честную середину — потолок срабатывает только на длинных.
IMAGE_FILM_TITLE_Y_MAX = 360

# Как подписан кадр, когда номер шага не прислали. ⚠ То же слово «шаг», что и
# у настоящей подписи: две разные нумерации на одной плёнке читались бы как
# ошибка. Чем эта подпись хуже настоящей — в `_film_label`.
IMAGE_FILM_LABEL = 'Шаг {no}'

# Цвета заставки и полосы с номером шага: тёмный фон, белый текст.
IMAGE_FILM_DARK = (30, 41, 59)
IMAGE_FILM_LIGHT = (255, 255, 255)

# Высота полосы с номером шага, в долях ширины кадра. ⚠ В долях, а не в
# точках: плёнку собирают и в 600, и в 1280 — полоса в 24 точки на широком
# кадре выглядит ниткой.
IMAGE_FILM_BADGE_PART = 0.04

# Насколько кегль подписи меньше полосы. ⚠ Не впритык: у букв есть выносные
# элементы («Ц», «р»), и текст в полную высоту полосы обрезается ими.
IMAGE_FILM_BADGE_FIT = 0.72


def image_film_same(before: bytes, after: bytes,
                    tolerance: int = IMAGE_FILM_TOLERANCE) -> bool:
    """Одинаковы ли два кадра на вид; `True` — ничего не изменилось.

    Args:
        before: кадр до шага, байты PNG или JPEG.
        after: кадр после.
        tolerance: сколько битов хеша прощаем (см. шапку).

    Returns:
        `True`, если кадры неотличимы на глаз. Пустой любой из них — `False`:
        «нечего сравнивать» это не «одинаковы», и терять кадр из-за сбоя
        снимка нельзя.

    ⚠ Не бросает на нечитаемом кадре: отвечает `False`. Снимок — свидетельство,
    и беда с одним кадром не должна рушить сбор остальных.

    >>> image_film_same(b'', b'')
    False
    """
    if not before or not after:
        return False

    try:
        return _hamming(_film_hash(before), _film_hash(after)) <= tolerance
    except Exception:  # noqa: BLE001 — кадр не стоит прогона
        return False


def image_film_gif(frames: list, out: str, ms: int = IMAGE_FILM_FRAME_MS,
                   width: int = IMAGE_FILM_WIDTH,
                   height: int = IMAGE_FILM_HEIGHT,
                   labels: list | None = None,
                   title: str = IMAGE_FILM_TITLE) -> dict:
    """Собрать GIF из кадров по порядку; вернуть, что получилось.

    Args:
        frames: кадры байтами, в порядке съёмки.
        out: куда записать `.gif`.
        ms: сколько держать кадр.
        width: до какой ширины ужимать.
        height: потолок высоты; `0` — не резать (умолчание, см. шапку).
        labels: подпись каждого кадра — обычно номер шага. Короче списка
            кадров или пусто — недостающие подписываются «кадр N».
        title: заставка первым кадром; пустая строка — без неё.

    Returns:
        `{'frames', 'bytes', 'path', 'error'}`. Кадров меньше двух — файл не
        пишется вовсе и приходит `error`: «плёнка» из одного кадра это просто
        кадр, и отдельный файл под него только путает.

    Raises:
        RuntimeError: нет Pillow.

    ⚠ Последний кадр держится дольше (`IMAGE_FILM_LAST_MS`): на нём итог, и
    без паузы плёнка возвращается к началу ровно тогда, когда на него
    посмотрели.

    ⚠⚠ Заставка в счёт кадров НЕ идёт: `frames` в ответе — сколько снято, а
    не сколько картинок в файле. Иначе число кадров у плёнки и у прогона
    расходились бы на единицу, и сверить их стало бы нечем.
    """
    if len(frames or []) < 2:
        return {'frames': len(frames or []), 'bytes': 0, 'path': '',
                'error': 'кадров меньше двух — плёнки не выйдет'}

    image = _pillow()
    shots = []
    for raw in frames:
        try:
            shots.append(_film_fit(image.open(io.BytesIO(raw)), width, height))
        except Exception:  # noqa: BLE001 — битый кадр пропускаем
            continue

    if len(shots) < 2:
        return {'frames': len(shots), 'bytes': 0, 'path': '',
                'error': 'читаемых кадров меньше двух'}

    # ⚠⚠ Все кадры одной высоты: GIF кладёт разные ДРУГ НА ДРУГА, и короткий
    # показывается с хвостом предыдущего. Как именно приводим — в `_film_align`.
    shots = _film_align(shots)
    taken = len(shots)

    # ⚠ Подпись рисуется ПОСЛЕ выравнивания и ДО палитры: после — чтобы
    # полоса легла по общей ширине, до — чтобы её цвета попали в палитру
    # кадра, а не подменились ближайшими.
    for at, shot in enumerate(shots):
        _film_badge(shot, _film_label(labels, at))

    if title:
        shots.insert(0, _film_title(shots[0].size, title))

    shots = _film_palette(shots)

    # ⚠ Длительность списком, а не числом: заставка и последний кадр держатся
    # дольше прочих — первую читают, на втором итог.
    hold = ([IMAGE_FILM_TITLE_MS] if title else []) \
        + [ms] * (taken - 1) + [IMAGE_FILM_LAST_MS]

    path = pathlib.Path(out)
    path.parent.mkdir(parents=True, exist_ok=True)
    shots[0].save(path, save_all=True, append_images=shots[1:],
                  duration=hold, loop=0, optimize=True)

    return {'frames': taken, 'bytes': path.stat().st_size,
            'path': str(path), 'error': ''}


# ── детали реализации ──────────────────────────────────────────────────────

def _pillow():
    """Модуль `Image` Pillow; нет его — отказ словами, а не `ImportError`."""
    try:
        from PIL import Image
    except ImportError as fault:
        raise RuntimeError('для плёнки нужен Pillow: pip install Pillow') \
            from fault

    return Image


def _film_hash(raw: bytes) -> int:
    """dHash кадра числом: знак перепада яркости между соседями.

    ⚠ Именно перепад, а не сами значения: так хеш не замечает общего
    осветления и шума сжатия, но ловит перерисовку — ради этого он и взят.
    """
    image = _pillow()
    small = image.open(io.BytesIO(raw)).convert('L').resize(
        (IMAGE_FILM_SIDE + 1, IMAGE_FILM_SIDE))
    dots = list(small.getdata())

    bits = 0
    for row in range(IMAGE_FILM_SIDE):
        line = row * (IMAGE_FILM_SIDE + 1)
        for col in range(IMAGE_FILM_SIDE):
            bits <<= 1
            if dots[line + col] > dots[line + col + 1]:
                bits |= 1

    return bits


def _hamming(one: int, two: int) -> int:
    """Сколько битов разошлось у двух хешей."""
    return bin(one ^ two).count('1')


def _film_align(shots: list) -> list:
    """Привести кадры к общей высоте; цвет остаётся полным (RGB).

    ⚠⚠ Без общей высоты GIF показывает хвосты: кадры разного размера он кладёт
    ДРУГ НА ДРУГА, и после высокого у низкого снизу остаётся чужая картинка.

    ⚠⚠ Холст — по МЕДИАНЕ, а не по самому высокому кадру. Страницы одного
    прогона разной длины: карточка товара вдвое длиннее формы заказа. По
    максимуму холст растягивается под единственный длинный кадр, и у
    остальных половина плёнки — белое поле. Замер: 2376 против 1100.

    ⚠ Кадр выше холста ужимается ЦЕЛИКОМ и центрируется, а не режется:
    обрезка отвечала бы на половину вопроса — ровно то, от чего уходили.
    Кадр ниже дотягивается белым полем снизу: там подвал страницы, и поле
    читается как её продолжение.

    ⚠ В палитру здесь НЕ переводим: поверх кадра ещё рисуется полоса с
    номером шага, и её цвета обязаны попасть в палитру вместе со всем
    остальным (`_film_palette`).
    """
    image = _pillow()
    heights = sorted(one.height for one in shots)
    tall = heights[len(heights) // 2]
    wide = max(one.width for one in shots)

    out = []
    for one in shots:
        if one.height > tall:
            thin = max(1, round(one.width * tall / one.height))
            one = one.resize((thin, tall), image.LANCZOS)

        if (one.width, one.height) != (wide, tall):
            field = image.new('RGB', (wide, tall), 'white')
            field.paste(one, ((wide - one.width) // 2, 0))
            one = field

        out.append(one if one.mode == 'RGB' else one.convert('RGB'))

    return out


def _film_palette(shots: list) -> list:
    """Кадры в палитру GIF — последним действием, когда всё нарисовано.

    ⚠⚠ Считается ПОСЛЕ выравнивания и подписей: иначе у кадров разный набор
    цветов, Pillow применяет к плёнке палитру первого, и остальные плывут.
    """
    image = _pillow()

    return [one.convert('P', palette=image.ADAPTIVE,
                        colors=IMAGE_FILM_COLORS) for one in shots]


def _film_label(labels, at: int) -> str:
    """Подпись кадра: что передали или свой порядковый номер.

    ⚠⚠ Запасная подпись говорит «шаг», как и переданная. Слово на картинке
    одно, и две формулировки («Шаг 7» на одних кадрах, «кадр 3» на других)
    читались бы как две разные нумерации одной плёнки.

    ⚠ Запасная при этом неточна, и знать это надо: кадр снимается только
    тогда, когда шаг что-то изменил, — третий кадр обычно седьмой шаг.
    Настоящие номера знает тот, кто снимал, и передаёт их списком; свой счёт
    нужен лишь там, где их не прислали.
    """
    given = labels[at] if labels and at < len(labels) else ''

    return str(given).strip() or IMAGE_FILM_LABEL.format(no=at + 1)


def _film_badge(shot, text: str) -> None:
    """Нарисовать поверх кадра тонкую тёмную полосу с подписью; правит на месте.

    ⚠⚠ Полоса НАКЛАДЫВАЕТСЯ на кадр, а не добавляется сверху. Добавленная
    меняла бы высоту, а она у всех кадров общая и уже посчитана по медиане —
    пришлось бы считать заново, и титр с кадрами разошёлся бы на её толщину.
    Жертвуем верхними двумя десятками точек: там шапка сайта, и она
    повторяется на каждом кадре.

    ⚠ Отказ молчит: подпись — удобство, а кадр без неё остаётся кадром.
    Ронять сборку плёнки из-за отсутствующего шрифта нельзя.
    """
    try:
        from PIL import ImageDraw

        from font_.font_pick import font_pick_covers, font_pick
    except ImportError:
        return

    high = max(14, round(shot.width * IMAGE_FILM_BADGE_PART))
    font = font_pick(max(9, round(high * IMAGE_FILM_BADGE_FIT)), text)
    if not font_pick_covers(font, text):
        return

    draw = ImageDraw.Draw(shot)
    draw.rectangle((0, 0, shot.width, high), fill=IMAGE_FILM_DARK)
    draw.text((shot.width // 2, high // 2), text, font=font,
              fill=IMAGE_FILM_LIGHT, anchor='mm')


def _film_title(size: tuple, text: str):
    """Заставка: тёмный кадр того же размера с текстом посередине.

    ⚠⚠ Размер БЕРЁТСЯ У КАДРОВ, а не задаётся. Кадр другого размера GIF кладёт
    поверх предыдущего, не стирая его: заставка в полэкрана оставила бы вокруг
    себя куски первой страницы.

    ⚠⚠ Надпись не опускается ниже `IMAGE_FILM_TITLE_Y_MAX`: на кадре в две
    тысячи точек геометрический центр не попадает в превью списка, и заставка
    выглядит пустой тёмной плиткой. На коротком кадре центр честный.

    ⚠ Нет кириллического шрифта — пишем латиницей (`IMAGE_FILM_TITLE_LATIN`):
    ряд пустых прямоугольников выглядит поломкой, а не подписью.
    """
    image = _pillow()
    wide, tall = size
    field = image.new('RGB', (wide, tall), IMAGE_FILM_DARK)

    try:
        from PIL import ImageDraw

        from font_.font_pick import font_pick_covers, font_pick
    except ImportError:
        return field

    say = str(text)
    font = font_pick(max(16, wide // 10), say)
    if not font_pick_covers(font, say):
        say = IMAGE_FILM_TITLE_LATIN
        font = font_pick(max(16, wide // 10), say)

    ImageDraw.Draw(field).text(
        (wide // 2, min(tall // 2, IMAGE_FILM_TITLE_Y_MAX)), say, font=font,
        fill=IMAGE_FILM_LIGHT, anchor='mm')

    return field


def _film_fit(shot, width: int, height: int):
    """Кадр, сжатый по ширине, в режиме GIF. Высота — целиком.

    ⚠⚠ Страница НЕ обрезается: по плёнке разбирают работу, и кадр без кнопок
    и итогов отвечает на половину вопроса. Читаемость чинится шириной.

    ⚠ `height` оставлен параметром, но по умолчанию `0` — «не резать». Он
    нужен тому, у кого страница в сорок экранов (бесконечная лента): там
    обрезка меньшее зло, чем кадр, который не откроется.

    ⚠⚠ Кадры в GIF должны быть ОДНОГО размера: разной высоты Pillow кладёт
    поверх предыдущего, и короткий кадр показывается с хвостом длинного.
    Поэтому все дотягиваются до самого высокого — белым полем снизу.

    ⚠ Перевод в палитру здесь, а не при записи: Pillow иначе считает её для
    первого кадра и применяет ко всем, и цвета остальных плывут.
    """
    image = _pillow()
    if shot.width > width:
        tall = max(1, round(shot.height * width / shot.width))
        shot = shot.resize((width, tall), image.LANCZOS)
    if height and shot.height > height:
        shot = shot.crop((0, 0, shot.width, height))

    return shot.convert('RGB')


def _main() -> int:
    parser = argparse.ArgumentParser(
        prog='python -m image_.image_film',
        description='Плёнка из кадров: GIF по порядку, без повторов.')
    parser.add_argument('shots', nargs='+', help='кадры по порядку')
    parser.add_argument('--out', default='film.gif', help='куда записать')
    parser.add_argument('--ms', type=int, default=IMAGE_FILM_FRAME_MS,
                        help='сколько держать кадр')
    parser.add_argument('--all', action='store_true',
                        help='не выбрасывать одинаковые подряд')
    args = parser.parse_args()

    film, last = [], b''
    for name in args.shots:
        raw = pathlib.Path(name).read_bytes()
        if args.all or not image_film_same(last, raw):
            film.append(raw)
            last = raw

    got = image_film_gif(film, args.out, args.ms)
    if got['error']:
        print(f'ошибка: {got["error"]}', file=sys.stderr)

        return 1

    print(f'{got["path"]}: кадров {got["frames"]}, '
          f'{got["bytes"] // 1024} КБ (из {len(args.shots)} снятых)')

    return 0


if __name__ == '__main__':
    raise SystemExit(_main())
