"""Круг: делать раз в N секунд, пока идёт смена.

Круг — это «просыпаться каждые N секунд и делать дело, пока не кончится смена».
Написанный руками, он всегда одни и те же четыре строки: сон, отмеренный до конца
смены; работа; отказ в журнал; снова сон. Копии таких четырёх строк разъезжаются
молча — где-то забыт потолок сна, где-то нижняя граница, где-то `except` поймал
не всё, — и расходятся они не в день правки, а через месяц, когда смена встала.

## ⚠ Отказ одного круга не конец смены

Смена стоит часами, и за это время у чужого сервиса бывает и перезапуск, и окно
техработ. Поэтому ловим **всё** `Exception`, а не перечисленные исключения:
уронить смену случайной `KeyError` из разбора чужого ответа дороже, чем круг
молчания до следующего тика.

⚠⚠ `asyncio.CancelledError` при этом **не ловится** — он наследник
`BaseException`, а не `Exception`. Это не случайность, а условие выключения:
остановка смены приходит именно отменой задачи, и проглоти мы её — процесс не
закончился бы вовсе.

## ⚠ Дедлайн монотонный, а не по часам

Конец смены считается `time.monotonic()`. Перевод системного времени или поправка
от NTP сдвинули бы его на произвольную величину, в том числе назад, — и смена
либо кончилась бы мгновенно, либо не кончилась никогда. Готовый дедлайн даёт
`round_deadline`; звать его, а не складывать `time.time()` руками.

## Что здесь есть, а чего нет

Здесь только скелет. Отметка «этой единице уже ходили» — в `round_slot.py`
(общая память, переживает смену) и `round_mem.py` (память процесса, не
переживает); обход единиц одним заходом — `round_pass.py`; суточная норма —
`round_day.py`.

**Смены здесь нет намеренно.** Смена — это «кто крутится и сколько», то есть
набор кругов конкретного проекта плюс его собственное хозяйство: у одного это
три круга и `asyncio.gather`, у другого двадцать один плюс держатель сокетов и
ожидание служебных задач. Общего у них ровно один вызов `round_deadline`.
Подробности — `docs/round.md`.
"""

import asyncio
import time
from collections.abc import Awaitable, Callable

from datetime_.datetime_ import datetime_offset_hours
from logging_.logging_ import logger_exception
from setting_.setting_ import setting_get

# Слово в квадратных скобках перед каждой строкой журнала круга. Смысл его один:
# в общем журнале сервера, где пишут несколько установок, по нему отбирают свои
# строки. Меняется один раз на процесс — `round_prefix_set`.
ROUND_PREFIX = 'round'

# Имя настройки часового пояса. То же, что читает `datetime_now` общего слоя:
# два имени для одного вопроса разошлись бы, и объяснить, почему расписание
# анкеты и показ времени живут в разных поясах, стало бы нечем.
ROUND_TIMEZONE_SETTING = 'timezone'

# Нижняя граница сна. ⚠ Остаток до дедлайна бывает долей секунды, и без границы
# цикл крутился бы вплотную, съедая процессор на пустых заходах.
ROUND_SLEEP_MIN_SEC = 1.0


def round_prefix(name: str = '') -> str:
    """Слово журнала: без довода — прочитать, с доводом — задать и вернуть.

    Args:
        name: новое слово. Пусто — только чтение.

    Returns:
        Слово, которое круги ставят в квадратных скобках.
    """
    global ROUND_PREFIX

    if str(name or '').strip():
        ROUND_PREFIX = str(name).strip()

    return ROUND_PREFIX


def round_prefix_set(name: str) -> str:
    """Назвать установку в журнале: `[dating]`, `[persona]`, `[crypto]`.

    Args:
        name: слово без скобок.

    Returns:
        То же слово — удобно писать в одну строку с проверкой.

    ⚠ **Зовётся один раз на процесс**, и лучше всего — на уровне модуля, который
    круги проекта и так все импортируют (у проекта это его собственный адаптер
    над слоем). Привяжи вызов к точке входа, и его придётся повторить в каждой:
    у воркера своя, у веб-приложения своя, у разового скрипта третья — забытая
    даст в журнале безымянный `[round]` ровно там, где строку будут искать.
    """
    return round_prefix(name)


def round_deadline(hold_sec: float) -> float:
    """Момент конца смены для `round_loop`: монотонные часы плюс выдержка.

    Args:
        hold_sec: сколько секунд держится смена.

    Returns:
        Значение в шкале `time.monotonic()`.

    ⚠ Функция в одну строку заведена ради одной ошибки, которую она исключает:
    `time.time() + hold_sec` выглядит так же и работает так же — до первой
    поправки часов. Сравнивать монотонное с календарным нельзя, а разницы на
    глаз не видно: оба `float`, оба «секунды».
    """
    return time.monotonic() + float(hold_sec)


async def round_loop(deadline: float, tick_sec: float, name: str,
                     body: Callable[[], Awaitable[None]]) -> None:
    """Крутит `body` до `deadline` с тиком `tick_sec`; отказ круга — в журнал.

    Args:
        deadline: момент по `time.monotonic()`, после которого круг кончается
            (`round_deadline`).
        tick_sec: пауза между заходами.
        name: имя круга для журнала — по нему отказ ищут.
        body: сама работа. Что вернёт — не смотрим, исключения ловятся здесь.

    Сначала сон, потом работа: смена только что поднялась, и начинать тяжёлое в
    первую её секунду незачем — а перезапуск, случившийся во время работы,
    повторил бы её немедленно.

    ⚠ Сон обрезаем остатком до дедлайна: тик крупнее остатка — и смена кончилась
    бы позже срока, а за ней в очереди стоит следующая.
    """
    while time.monotonic() < deadline:
        left = max(ROUND_SLEEP_MIN_SEC, deadline - time.monotonic())
        await asyncio.sleep(min(float(tick_sec), left))

        try:
            await body()
        except Exception as e:
            # Не просто текст: «'NoneType' object has no attribute 'get'» без
            # кадров не показывает, кто именно вернул не то.
            logger_exception(f'[{ROUND_PREFIX}] круг {name}: {e}', exc=e)


async def round_offset_loop(deadline: float, tick_sec: float, name: str,
                            body: Callable[[int], Awaitable[None]],
                            setting: str = '') -> None:
    """То же, но `body` получает часовое смещение — перечитанным каждым кругом.

    Args:
        deadline: момент по `time.monotonic()`, после которого круг кончается.
        tick_sec: пауза между заходами.
        name: имя круга для журнала.
        body: работа; получает смещение целым числом часов.
        setting: имя настройки пояса. Пусто — `ROUND_TIMEZONE_SETTING`.

    ⚠ Смещение читаем **каждый круг**, а не один раз на смену: настройку правят
    на ходу, и запомненное значение означало бы расписание по старому поясу до
    конца смены — то есть часы.

    ⚠ Отказ чтения настройки сюда не просачивается: он случается внутри `body`
    по месту вызова и ловится общим `except` `round_loop`.
    """
    key = str(setting or ROUND_TIMEZONE_SETTING)

    async def _with_offset() -> None:
        await body(datetime_offset_hours(await setting_get(key, '+0')))

    await round_loop(deadline, tick_sec, name, _with_offset)
