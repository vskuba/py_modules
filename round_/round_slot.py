"""Отметка захода в общей памяти: пора ли этой единице, и «уже ходили».

Круг просыпается часто, а дело делается редко: тик — минута, а обойти единицу
надо раз в полчаса. Разницу между «как часто просыпаемся» и «как часто идём»
держит отметка с собственным сроком: поставили — значит ходили, и пока она жива,
этой единице не пора.

## ⚠ Срок отметки **и есть** настройка

Отдельного «когда можно снова» мы не храним: отметка кладётся с выдержкой,
равной сроку круга, и гаснет сама. Поэтому правка настройки действует со
следующего же захода, а не после перезапуска, и «сколько осталось» не надо
считать — вопрос один: `есть отметка?`.

## ⚠⚠ Отметка ставится **до** дела, а не после

Дело идёт минутами — вызовы модели, вкладка браузера, обход страниц. Отметь мы
после, соседний тик успел бы завести второе такое же поверх первого. Цена
ошибки в эту сторону — пропущенный заход; в обратную — двойная работа, а у
занятий, которые ходят наружу, ещё и подозрение со стороны чужого сервиса.

## ⚠ Сомнение решается бездействием

Общая память бывает недоступна. Прочитать не удалось — отвечаем «не пора»:
лишний заход стоит дела (вызовы модели, вкладка браузера), пропущенный — только
задержки. Где цена ошибок несимметрична, сомнение решается молчанием.

Поставить не удалось — говорим в журнал и идём: заход важнее отметки. Снять не
удалось — молчим вовсе, отметка всё равно погаснет по сроку.

## Чем отличается от `round_mem.py`

| | `round_slot` | `round_mem` |
|---|---|---|
| где живёт | общая память (Redis) | словарь в памяти процесса |
| переживает перезапуск | да | нет |
| видна соседним процессам | да | нет |
| цена вопроса | запрос к Redis | сравнение двух чисел |

Выбор не про вкус: если заход стоит дорого и его нельзя повторять после
перезапуска смены — слот. Если перезапуск стоит одного лишнего захода и
ошибаться туда безопасно — память процесса.
"""

from logging_.logging_ import logger_info
from redis_.redis_ import redis_conn_get

from round_.round_ import round_prefix

# Метка единицы в шаблоне ключа. ⚠ Одна на слой: шаблон с чужой меткой молча
# остался бы ключом с фигурными скобками внутри — то есть одним общим слотом на
# все единицы, и круг ходил бы к одной из них вместо всех.
ROUND_SLOT_MARK = '{id}'

# Нижняя граница выдержки. Нулевой срок общая память не принимает — отметка не
# поставилась бы вовсе, и круг ходил бы каждым тиком.
ROUND_SLOT_EVERY_MIN = 1


def round_slot_key(key: str, unit=None) -> str:
    """Готовый ключ отметки: шаблон плюс единица обхода.

    Args:
        key: ключ целиком либо шаблон с меткой `{id}`.
        unit: единица обхода (номер сайта, аккаунта, устройства). `None` —
            ключ уже готов.

    Returns:
        Строку ключа.

    ⚠ Метка подставляется, только если она в шаблоне есть: ключ без метки —
    законный случай «слот один на всю установку» (так ходят уборщики и сверки,
    у которых единиц обхода нет вовсе).
    """
    text = str(key)

    return text.replace(ROUND_SLOT_MARK, str(unit)) if unit is not None else text


def round_slot_due(key: str, unit=None, what: str = '') -> bool:
    """Пора ли идти этой единице; отметки ещё нет — пора.

    Args:
        key: ключ или шаблон с `{id}`.
        unit: единица обхода; `None` — ключ готов.
        what: чей слот — словом, для журнала («рассылке», «панели»).

    Returns:
        `True` — пора; `False` — отметка жива либо память не ответила.

    ⚠⚠ Сбой читается как «не пора» (см. заголовок файла): где цена ошибок
    несимметрична, сомнение решается молчанием.
    """
    try:
        return not redis_conn_get().get(round_slot_key(key, unit))
    except Exception as e:
        logger_info(f'[{round_prefix()}] отметка {what} не прочиталась: {e}')

        return False


def round_slot_mark(key: str, unit=None, every: float = 0,
                    what: str = '') -> None:
    """Отмечает заход: следующему `every` секунд сюда нельзя.

    Args:
        key: ключ или шаблон с `{id}`.
        unit: единица обхода; `None` — ключ готов.
        every: срок в секундах — он же выдержка отметки.
        what: чей слот — словом, для журнала.

    ⚠ Ноль поднимаем до секунды: нулевую выдержку память не принимает, отметка
    не поставилась бы вовсе — и круг ходил бы каждым тиком, то есть настройка
    «ноль» означала бы ровно обратное задуманному.
    """
    try:
        redis_conn_get().setex(round_slot_key(key, unit),
                               max(ROUND_SLOT_EVERY_MIN, int(every or 0)), '1')
    except Exception as e:
        logger_info(f'[{round_prefix()}] отметка {what} не поставилась: {e}')


def round_slot_release(key: str, unit=None, what: str = '') -> None:
    """Снимает отметку: захода не было — и держать слот нечем.

    Args:
        key: ключ или шаблон с `{id}`.
        unit: единица обхода; `None` — ключ готов.
        what: чей слот — словом, для журнала.

    Нужна там, где шлюз уже пройден и отметка поставлена, а дело не состоялось
    по причине, которая пройдёт сама (нечего делать, никого нет в сети). Держать
    слот в этом случае значит ждать полчаса ради ничего.

    ⚠ Сбой глотаем молча: отметка погаснет по сроку сама, а уронить обход
    остальных единиц из-за неубранного ключа — цена заметно выше.
    """
    try:
        redis_conn_get().delete(round_slot_key(key, unit))
    except Exception as e:
        logger_info(f'[{round_prefix()}] отметка {what} не снялась: {e}')
