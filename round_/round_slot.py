"""Отметка захода в общей памяти: пора ли этой единице, и «уже ходили».

Круг просыпается часто, а дело делается редко: тик — минута, а обойти единицу
надо раз в полчаса. Разницу между «как часто просыпаемся» и «как часто идём»
держит отметка с собственным сроком: поставили — значит ходили, и пока она жива,
этой единице не пора.

## ⚠ Срок отметки **и есть** настройка

Отдельного «когда можно снова» мы не храним: отметка кладётся с выдержкой,
равной сроку круга, и гаснет сама. Поэтому правка настройки действует без
перезапуска.

⚠ Но одной самогасимости мало: отметка, поставленная по прежнему сроку,
додержала бы его до конца — человек поправил час на три минуты, а круг
«держит» ещё сорок (живьём: правка `template_every` на панели, а счётчик
«заход через 41 мин» стоит по-старому). Поэтому отметка хранит **свой срок
значением**, а `due` и `left` с доводом `every` сверяют его с настройкой
сегодня: срок меряется от захода, а не от дня постановки отметки. Поправил
60 на 3 — если последний заход был дальше трёх минут назад, на ближайшем
тике круг идёт; поправил 3 на 60 — следующий заход отодвигается до часа от
него. Выдержку ключа Redis мы переставить не можем, так что при удлинении
срока отметка доживает старую и гаснет — это один заход раньше нового темпа,
не больше: следующий тик отметит уже новый срок.

Без `every` обе функции отвечают по-старому — «есть отметка?»: слой не знает,
настройка это или константа, и угадывать не вправе.

## ⚠⚠ Отметка ставится **до** дела, а не после

Дело идёт минутами — вызовы модели, вкладка браузера, обход страниц. Отметь мы
после, соседний тик успел бы завести второе такое же поверх первого. Цена
ошибки в эту сторону — пропущенный заход; в обратную — двойная работа, а у
занятий, которые ходят наружу, ещё и подозрение со стороны чужого сервиса.

## ⚠ Сомнение решается бездействием — но решает его круг

Общая память бывает недоступна. Прочитать не удалось — по умолчанию отвечаем
«не пора»: лишний заход стоит дела (вызовы модели, вкладка браузера),
пропущенный — только задержки. Где цена ошибок несимметрична, сомнение решается
молчанием.

⚠⚠ Умолчание — не правило: у кого цена перевёрнута, тот говорит
`unknown=True`. Слой не знает, что дороже, и угадывать не вправе; подробности и
живой случай — в докстринге `round_slot_due`.

Поставить не удалось — говорим в журнал и идём: заход важнее отметки. Снять не
удалось — молчим вовсе, отметка всё равно погаснет по сроку.

## Чем отличается от `round_mem.py`

| | `round_slot` | `round_mem` |
|---|---|---|
| где живёт | общая память (Redis) | словарь в памяти процесса |
| переживает перезапуск | да | нет |
| видна соседним процессам | да | нет |
| цена вопроса | запрос к Redis | сравнение двух чисел |

Выбор не про вкус: если заход стоит дорого и его нельзя повторять после
перезапуска смены — слот. Если перезапуск стоит одного лишнего захода и
ошибаться туда безопасно — память процесса.
"""

from logging_.logging_ import logger_info
from redis_.redis_ import redis_conn_get

from round_.round_ import round_prefix

# Метка единицы в шаблоне ключа. ⚠ Одна на слой: шаблон с чужой меткой молча
# остался бы ключом с фигурными скобками внутри — то есть одним общим слотом на
# все единицы, и круг ходил бы к одной из них вместо всех.
ROUND_SLOT_MARK = '{id}'

# Нижняя граница выдержки. Нулевой срок общая память не принимает — отметка не
# поставилась бы вовсе, и круг ходил бы каждым тиком.
ROUND_SLOT_EVERY_MIN = 1


def round_slot_key(key: str, unit=None) -> str:
    """Готовый ключ отметки: шаблон плюс единица обхода.

    Args:
        key: ключ целиком либо шаблон с меткой `{id}`.
        unit: единица обхода (номер сайта, аккаунта, устройства). `None` —
            ключ уже готов.

    Returns:
        Строку ключа.

    ⚠ Метка подставляется, только если она в шаблоне есть: ключ без метки —
    законный случай «слот один на всю установку» (так ходят уборщики и сверки,
    у которых единиц обхода нет вовсе).
    """
    text = str(key)

    return text.replace(ROUND_SLOT_MARK, str(unit)) if unit is not None else text


def round_slot_due(key: str, unit=None, what: str = '',
                   unknown: bool = False, every: float | None = None) -> bool:
    """Пора ли идти этой единице; отметки ещё нет — пора.

    Args:
        key: ключ или шаблон с `{id}`.
        unit: единица обхода; `None` — ключ готов.
        what: чей слот — словом, для журнала («рассылке», «панели»).
        unknown: что ответить, если спросить не удалось. По умолчанию «не
            пора» — см. ниже.
        every: срок круга **сейчас**, в секундах. С ним правка настройки
            видна сразу: срок меряется от захода, а не от выдержки отметки
            (см. заголовок файла). Без него — прежнее «есть отметка?».

    Returns:
        `True` — пора; `False` — отметка жива.

    ⚠⚠ **Сторона решения при сбое — довод вызывающего, а не правило слоя**, и
    это та же мысль, что у `unknown` в `round_day.py`: слой не знает, что
    дороже. Умолчание стоит на «не пора», потому что так у большинства:
    лишний заход платит вызовами модели и вкладкой браузера, пропущенный —
    только задержкой.

    ⚠ Но бывает ровно наоборот, и тогда довод обязателен. Забор чужой
    переписки: пропущенный заход означает, что сообщение полежит до
    следующего круга, — **и это замечает человек** («она не отвечает»);
    лишний стоит сорока секунд, которых не замечает никто. Там
    `unknown=True`, и написать это доводом честнее, чем держать рядом свою
    копию функции с перевёрнутым `return`.
    """
    try:
        slot = round_slot_key(key, unit)
        mark = redis_conn_get().get(slot)
        if mark is None:
            return True

        if every is None:
            return False

        # Прошедшее с захода — выдержка минус живой остаток; пора, когда оно
        # дотянуло до **текущего** срока. Отметки прежнего слоя несли `'1'`:
        # выдержка выходит нулевая и ответ — «отметка жива», то есть ровно
        # прежнее поведение на ключах, поставленных до этой правки.
        left = int(redis_conn_get().ttl(slot))
        was = int(mark)
    except Exception as e:
        logger_info(f'[{round_prefix()}] отметка {what} не прочиталась: {e}')

        return bool(unknown)

    if left == -2:                      # ключ погас между двумя вопросами
        return True
    if left < 0:                        # ключ без срока — слой таких не ставит
        return False

    return was - int(every) >= left


def round_slot_left(key: str, unit=None, what: str = '',
                    every: float | None = None) -> int:
    """Сколько секунд до следующего захода этой единицы. `0` — можно сейчас.

    Args:
        key: ключ или шаблон с `{id}`.
        unit: единица обхода; `None` — ключ готов.
        what: чей слот — словом, для журнала («инвайтам», «ответам»).
        every: срок круга **сейчас**, в секундах; с ним счётчик честен сразу
            после правки настройки (`round_slot_due`). Без него — прежнее
            «сколько до гашения ключа».

    Returns:
        int: секунды до того, как отметка погаснет. `0` — отметки нет, круг
        возьмётся за единицу на ближайшем тике. `-1` — спросить не вышло.

    ⚠ **Это не `round_slot_due` с другим ответом.** Тот отвечает «да или нет» и
    при сбое общей памяти молчит в сторону «не пора» — лишний заход там дороже
    пропущенного. Здесь ответ — число секунд, и сторона ошибки своя: `-1`,
    «врать сроком нельзя». Два разных вопроса — две функции с именами, а не одна
    с флагом.

    ⚠⚠ **Заведена потому, что её писали копиями, и копии ломались.** Два круга
    соседнего проекта держали её у себя дословно, и обе подставляли единицу в
    ключ сами — `KEY.format(site_id=…)` на шаблоне с меткой `{id}`. `.format`
    бросал `KeyError`, его глотал `except`, и счётчик «следующий заход через N»
    молча отвечал «спросить не вышло» на живой отметке со сроком 1767 секунд.
    Страница не показывала срок месяцами, и выглядело это как «данных нет», а не
    как поломка.

    Лекарство не в том, чтобы поправить обе, а в том, чтобы подставлять ключ
    руками стало неоткуда: здесь это делает `round_slot_key`, и метка у него одна
    на весь слой (`ROUND_SLOT_MARK`).
    """
    try:
        slot = round_slot_key(key, unit)
        left = int(redis_conn_get().ttl(slot))

        if every is not None and left > 0:
            # Тот же пересчёт, что в `round_slot_due`: срок от захода, а не от
            # выдержки ключа. `due` и `left` считают одинаково — страница и круг
            # не разъедутся (графля, случавшаяся в этом проекте дважды).
            left -= max(0, int(redis_conn_get().get(slot)) - int(every))
    except Exception as e:
        logger_info(f'[{round_prefix()}] срок {what} не спросился: {e}')

        return -1

    # `-2` — ключа нет, `-1` — ключ есть, но без срока. Первое значит «пора»,
    # второе мы завести не можем (ставим только `setex`), но отвечать на него
    # сроком всё равно нельзя.
    return 0 if left == -2 else max(0, left)


def round_slot_mark(key: str, unit=None, every: float = 0,
                    what: str = '') -> None:
    """Отмечает заход: следующему `every` секунд сюда нельзя.

    Args:
        key: ключ или шаблон с `{id}`.
        unit: единица обхода; `None` — ключ готов.
        every: срок в секундах — он же выдержка отметки **и её значение**:
            по нему `due` и `left` пересчитывают срок, когда настройку
            поправят (см. заголовок файла).
        what: чей слот — словом, для журнала.

    ⚠ Ноль поднимаем до секунды: нулевую выдержку память не принимает, отметка
    не поставилась бы вовсе — и круг ходил бы каждым тиком, то есть настройка
    «ноль» означала бы ровно обратное задуманному.
    """
    try:
        held = max(ROUND_SLOT_EVERY_MIN, int(every or 0))
        redis_conn_get().setex(round_slot_key(key, unit), held, str(held))
    except Exception as e:
        logger_info(f'[{round_prefix()}] отметка {what} не поставилась: {e}')


def round_slot_release(key: str, unit=None, what: str = '') -> None:
    """Снимает отметку: захода не было — и держать слот нечем.

    Args:
        key: ключ или шаблон с `{id}`.
        unit: единица обхода; `None` — ключ готов.
        what: чей слот — словом, для журнала.

    Нужна там, где шлюз уже пройден и отметка поставлена, а дело не состоялось
    по причине, которая пройдёт сама (нечего делать, никого нет в сети). Держать
    слот в этом случае значит ждать полчаса ради ничего.

    ⚠ Сбой глотаем молча: отметка погаснет по сроку сама, а уронить обход
    остальных единиц из-за неубранного ключа — цена заметно выше.
    """
    try:
        redis_conn_get().delete(round_slot_key(key, unit))
    except Exception as e:
        logger_info(f'[{round_prefix()}] отметка {what} не снялась: {e}')
