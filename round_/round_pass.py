"""Заход: обойти единицы одним телом — шлюз, отметка до дела, само дело.

Круг — это «раз в N секунд»; заход — одно его срабатывание. У круга, который
ведёт не одну вещь, а много (сайты, аккаунты, устройства), заход всегда одной
формы:

```text
для каждой единицы:
    шлюз не пустил — следующая
    отметить заход по сроку этой единицы     ← до дела, а не после
    сделать дело, итог сложить в ответ
```

Четыре строки, и каждый круг писал их заново. Расходились они не формой, а
мелочами: один отмечал после дела, другой забывал, что срок у единиц разный,
третий ронял обход остальных из-за отказа у первой.

## ⚠ Шлюз отвечает целиком, обеими половинками

`gate` — это и выключатель занятия, и часы смены, и срок круга, и — где
бывает — будильник, велящий зайти раньше срока. Половинки у кругов разные:
одному чистка обязана и при молчащем наборе, другому лента будит заход
досрочно. Разведи их на два довода, и ни один не ответил бы за оба.

## ⚠⚠ Итог считает круг, а не заход

`work` возвращает что угодно, и это «что угодно» просто складывается в ответ
парами `(единица, итог)`. Складывать числа здесь нельзя: у одного круга итог —
«сколько сочинили», у другого «сколько проверили» и «сколько из них в сети», у
третьего словарь с четырьмя счётчиками. Заход о них не знает и знать не должен.

Там же живёт и решение «отпустить ли слот»: заход впустую слот держать не
должен, но что считать «впустую», знает круг — у него рядом лежат и причины, и
слова для журнала (`round_slot_release`).

## ⚠ Отказ единицы: по умолчанию роняет обход

`keep_going=False` — отказ летит наружу, до `round_loop`, и остальные единицы
этого захода не обходятся. Это правильно, когда отказ у одной означает отказ у
всех (упала база, лёг общий сервис): пройти остальные значило бы собрать ту же
ошибку ещё десять раз.

`keep_going=True` — отказ пишется в журнал, обход продолжается. Это правильно,
когда единицы независимы: у одного сайта сменилась вёрстка, у другого занят пул
браузеров — прочим это не мешает.

⚠ Выбор между ними — решение круга, не слоя. Умолчание стоит на «роняет»
только потому, что это поведение рукописных заходов, с которых слой собран:
молчаливая смена на «продолжает» спрятала бы отказы, которые сейчас видны.
"""

from collections.abc import Awaitable, Callable

from datetime_.datetime_ import datetime_day_minutes
from logging_.logging_ import logger_exception

from round_.round_ import round_prefix
from round_.round_slot import round_slot_mark


async def round_pass_run(rows: list, *,
                         work: Callable[..., Awaitable],
                         gate: Callable[..., Awaitable[bool]] | None = None,
                         every: Callable[..., Awaitable] | None = None,
                         key: str = '', what: str = '',
                         unit_of: Callable | None = None,
                         offset_hours: int = 0,
                         keep_going: bool = False) -> list[tuple]:
    """Обходит единицы одним скелетом; отдаёт пары «единица — итог».

    Args:
        rows: единицы обхода. Числа, словари, кортежи — что отдал запрос.
        work: дело. Зовётся `work(row, minutes)`; возвращает что угодно.
        gate: шлюз. Зовётся `gate(row, minutes)`; `None` — пускаем всех.
        every: срок этой единицы в секундах. Зовётся `every(unit)`.
            Обязателен, когда задан `key`.
        key: ключ слота или шаблон с `{id}`. Пусто — заход слота не ставит
            (у круга либо нет единиц, либо его темп держится иначе).
        what: чей заход — словом, для журнала.
        unit_of: как достать единицу из строки. `None` — `row['id']` у
            словаря, сама строка у всего прочего.
        offset_hours: часовое смещение; из него считаются местные минуты суток,
            которые уезжают в `gate` и `work`.
        keep_going: глотать ли отказ одной единицы (см. заголовок файла).

    Returns:
        Список пар `(строка, итог work)` — только по тем единицам, что прошли
        шлюз. Не прошедшие в ответе не появляются вовсе: «не пошли» и «пошли и
        ничего не вышло» — разные вещи, и считает их круг.

    Raises:
        ValueError: задан `key` без `every` — слот поставить нечем.
    """
    if key and every is None:
        raise ValueError('задан `key` без `every`: срок отметки взять негде')

    out: list[tuple] = []
    minutes = datetime_day_minutes(offset_hours)
    pick = unit_of or _unit_default

    for row in rows or []:
        try:
            unit = pick(row)

            if gate is not None and not await gate(row, minutes):
                continue

            # ⚠ Отметка до дела: набор идёт минутами, и следующий тик завёл бы
            # второй поверх первого (`round_slot.py`).
            if key:
                round_slot_mark(key, unit, await every(unit), what)

            out.append((row, await work(row, minutes)))
        except Exception as e:
            if not keep_going:
                raise

            # Имя занятия приписываем, только если оно названо: «заход ,
            # единица #3» с висящей запятой читается как опечатка в коде.
            logger_exception(
                f'[{round_prefix()}] заход{" " + what if what else ""},'
                f' единица #{_said(row, pick)}: {e}', exc=e)

    return out


def _unit_default(row):
    """Единица обхода по умолчанию: `id` у словаря, сама строка у прочего."""
    return row['id'] if isinstance(row, dict) else row


def _said(row, pick) -> str:
    """Как назвать единицу в строке журнала, когда достать её не удалось.

    ⚠ Своей защитой, а не вызовом `pick` второй раз: отказ мог случиться
    **внутри** `pick` (нет такого ключа в строке), и повторный вызов уронил бы
    журнал вместо обхода — то есть отнял бы ровно ту строку, по которой беду
    находят.
    """
    try:
        return str(pick(row))
    except Exception:
        return '?'
