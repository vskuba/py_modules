"""Суточная норма: сколько уже сделано за местные календарные сутки.

Третий способ придержать круг, рядом со слотом и темпом, и отвечает он на другой
вопрос. Слот говорит «не чаще, чем раз в N секунд», темп — то же, но дешевле;
норма говорит «не больше, чем N штук за сутки». Первые два — про частоту, третий
— про количество, и подменять их друг другом нельзя: пауза в минуту не мешает
уйти тысяче писем, а норма в сто штук не мешает им уйти за одну минуту.

## ⚠ Сутки местные, а не серверные

База живёт по UTC, а смены и панель — по местному времени. Считай мы норму по
серверным суткам, при смещении в три часа она кончалась бы в три ночи — и
человек, которому обещали «сто писем в сутки», получал бы их в непонятных ему
границах.

## ⚠ Дата считается один раз, а не дважды

Два запроса, и `NOW()` внутри каждого, разошлись бы на границе суток: первый
успел бы ответить «вчера», второй сказал бы «сегодня». Редко — но именно на
границе это и важно, потому что там норма обнуляется.

## ⚠⚠ Что значит сбой — решает круг, а не слой

Сбой чтения возвращает `unknown`, и выбор этого числа принципиален. Нулём его
ставят там, где лучше пойти (норму считают по журналу, пропущенный заход дороже
лишнего); потолком (`10 ** 6`) — там, где лучше промолчать: не ответила база,
значит счёта нет, а слать живым людям «сколько получится» нельзя.

Слой не угадывает: у него нет ни знания про занятие, ни права решать за него.
"""

from logging_.logging_ import logger_info
from mysql_.mysql_ import mysql_get_db_async
from sql_.sql_build import SQL_BUILD_NAME_RE

from round_.round_ import round_prefix


async def round_day_count(table: str, where: dict, *,
                          date_column: str, offset_hours: int = 0,
                          unknown: int = 0, what: str = '') -> int:
    """Сколько строк таблицы попадает в местные календарные сутки.

    Args:
        table: таблица.
        where: чем отобрать строки — «столбец: значение», сравнение через `=`.
            Пусто не бывает: норма без отбора считала бы всю установку разом.
        date_column: столбец с датой события, по которому идёт отбор суток.
        offset_hours: часовое смещение местного времени.
        unknown: что вернуть при сбое чтения (см. заголовок файла).
        what: чья норма — словом, для журнала.

    Returns:
        Число строк либо `unknown`, если спросить не удалось.

    Raises:
        ValueError: негодное имя таблицы или столбца, либо пустой `where`.

    ⚠ Имена таблицы и столбцов уезжают в запрос **текстом** — идентификатор
    подстановкой не передаётся ни в одной базе. Поэтому они проверяются на
    входе, и это единственная защита от чужого текста в запросе к боевой схеме.
    Значения `where` при этом идут подстановкой, как положено.
    """
    if not where:
        raise ValueError('нужен `where`: норма без отбора считает всю установку')

    name = _name(table)
    date_name = _name(date_column)
    cols = [_name(one) for one in where]
    hours = int(offset_hours or 0)
    tail = ' AND '.join(f'`{one}` = %s' for one in cols)

    try:
        async with mysql_get_db_async() as db:
            await db.execute('SELECT DATE(NOW() + INTERVAL %s HOUR) AS d',
                             (hours,))
            today = ((await db.fetchone()) or {}).get('d')

            await db.execute(
                f'SELECT COUNT(*) AS n FROM `{name}`'
                f' WHERE {tail}'
                f'   AND DATE(`{date_name}` + INTERVAL %s HOUR) = %s',
                (*where.values(), hours, today))
            row = await db.fetchone()
    except Exception as e:
        logger_info(f'[{round_prefix()}] дневной счёт {what} не спросился: {e}')

        return int(unknown)

    return int((row or {}).get('n') or 0)


def _name(name: str) -> str:
    """Имя таблицы или столбца — или отказ.

    ⚠ Правило и выражение те же, что у `sql_build`: второй свой список
    разрешённых знаков разошёлся бы с первым молча.
    """
    text = str(name)
    if not SQL_BUILD_NAME_RE.fullmatch(text):
        raise ValueError(f'негодное имя: {text!r}')

    return text
