"""Темп в памяти процесса: когда этот ключ ходил в последний раз.

Самый дешёвый способ развести «как часто просыпаемся» и «как часто идём»:
словарь `{ключ: время}` и сравнение двух чисел. Ни запроса, ни сети, ни отказа,
который надо обрабатывать.

## ⚠ Чем платим: перезапуск забывает темп

Словарь живёт в памяти процесса. Поднялась новая смена — он пуст, и первый же
тик считает, что идти пора всем. Для занятий, где лишний заход стоит одной
лишней строки или одного лишнего запроса, это правильный размен: простота против
точности на границе смены. Там, где лишний заход стоит письма живому человеку
или вкладки браузера, нужен `round_slot.py` — его отметка перезапуск переживает.

## ⚠ Ключ произвольный, и это важнее, чем кажется

Ключом бывает не только единица обхода: у круга, который ведёт несколько
занятий по одной единице, темп у каждого свой, и ключ составной — `(сайт,
таблица)`. Один ключ на двоих означал бы, что быстрое занятие съедает срок
медленного, и объяснить, почему письмо ушло на двадцать минут позже, было бы
нечем.

## ⚠⚠ Отметка ставится до дела, по той же причине, что у слота

Отправка идёт секунды, а тик бывает и секундным: не отметь мы сразу, соседний
тик взял бы ту же работу, пока первый ждёт ответа. Разница со слотом только в
том, где лежит отметка, — правило одно.

## Часы здесь календарные, а не монотонные

`time.time()`, а не `time.monotonic()`: словарь переживает отдельные заходы, но
не процесс, и сравнивать его значения с монотонными часами другого процесса всё
равно не придётся. Цена поправки часов — один сдвинутый заход; цена путаницы
двух шкал в одном словаре — заход, не случившийся никогда.
"""

import time


def round_mem_due(mem: dict, key, every: float) -> bool:
    """Вышел ли темп этого ключа: с прошлого захода прошло не меньше `every`.

    Args:
        mem: словарь темпа — свой у каждого круга, заводится на уровне модуля.
        key: что отмечаем. Единица обхода, пара «единица и занятие», имя
            занятия — что угодно хешируемое.
        every: срок в секундах.

    Returns:
        `True` — пора.

    ⚠ Первый заход — всегда пора: ключа в словаре нет, а значит не было ещё ни
    одного захода. Это не «ошибка в сторону лишней работы», а единственное
    верное чтение пустоты.
    """
    return time.time() - mem.get(key, 0.0) >= float(every or 0)


def round_mem_mark(mem: dict, key) -> None:
    """Запомнить момент захода — темп отсчитывается от него.

    Args:
        mem: тот же словарь, что у `round_mem_due`.
        key: тот же ключ.

    ⚠ Зовётся **до** дела, а не после (см. заголовок файла).
    """
    mem[key] = time.time()
