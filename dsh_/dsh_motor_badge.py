"""Значок мотора DSH для терминала: цифра на цветной плашке — своя у каждого мотора.

Мотор — параллельная цепочка модели на доске DSH (по умолчанию 4). Значок ставится в
строке «DSH 4/4: …» перед подписью работы и в таблице сессий Claude Code напротив
сессии-хозяина: одинаковые цифра и цвет связывают работу с сессией одним взглядом.

Субагент ждёт ответа человека — за цифрой мотора `?` (`dsh_motor_badge_ask`): оранжевая
плашка; статусная строка на нечётных секундах гасит её до тёмной — так он мигает.

⚠ Значок кончается полным сбросом цвета (`\\x1b[0m`): кто красит строку вокруг, должен
вернуть свой цвет после него (статусная строка так и делает).
"""

# Цвет плашки мотора по номеру (256-цветная палитра); дальше — по кругу.
DSH_MOTOR_BADGE_COLORS = (117, 114, 215, 228, 183, 222, 152, 174)


# Плашка «ждёт ответа»: оранжевый фон — по нему статусная строка находит её и мигает.
DSH_MOTOR_BADGE_ASK = '\x1b[1;38;5;16;48;5;208m?\x1b[0m'


def dsh_motor_badge_ask() -> str:
    """Знак «ждёт ответа человека» — `?` на оранжевой плашке; статусная строка его мигает."""
    return DSH_MOTOR_BADGE_ASK


def dsh_motor_badge(motor) -> str:
    """Цифра мотора на его цветной плашке; номер не число — серая плашка с «?»."""
    try:
        number = int(motor)
    except (TypeError, ValueError):
        return '\x1b[1;38;5;16;48;5;245m?\x1b[0m'
    color = DSH_MOTOR_BADGE_COLORS[(number - 1) % len(DSH_MOTOR_BADGE_COLORS)]
    return f'\x1b[1;38;5;16;48;5;{color}m{number}\x1b[0m'
