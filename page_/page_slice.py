"""Страница списка: смещение, предел и число страниц — одним ответом.

Арифметика страниц выглядит на три строки и пишется заново в каждом списке:
`offset = (page - 1) * per_page`, `pages = max(1, -(-total // per_page))`. К
моменту появления этого модуля она лежала **в шести местах трёх проектов** —
покупатели, отпечатки, сессии, блоки, намерения, журнал, — и везде чуть
по-разному.

Беда не в объёме, а в краях: страница меньше единицы, нулевой `per_page`,
пустой список, номер страницы больше, чем их есть. Каждая копия ошибается в
своём крае, и ошибка видна не сразу — список просто показывает не то.

## ⚠⚠ `pages` не бывает нулём

Пустой список — это **одна** страница, а не ноль: страница существует, она
просто пуста. Ноль здесь означал бы «страниц нет вовсе», и пейджер показывал
бы «1 из 0».

## ⚠ Номер страницы подрезается, а не отвергается

Человек нажал «вперёд» на последней, список за это время ужался — просить
отказ незачем: отдаётся последняя существующая. Отказ здесь означал бы пустой
экран вместо списка, который никуда не делся.

## ⚠ Ответ одной формы на все списки

`page_answer` собирает конверт, который ждёт общий пейджер панели
(`dashboard/js/pager.js`): `rows`, `total`, `page`, `pages`, `per_page`,
`shown`. Своя форма у каждого списка означала бы свой пейджер у каждой
страницы — ровно то, от чего уходим.
"""

# Сколько строк на странице, если зовущий не сказал. ⚠ Полсотни — не вкус:
# столько влезает на экран ноутбука без прокрутки таблицы, а больше человек
# всё равно не читает, он листает.
PAGE_SLICE_PER_PAGE = 50

# Потолок строк на странице. ⚠ Нужен против `?per_page=100000` из адресной
# строки: такой запрос отдаёт браузеру таблицу, которую он рисует секунду, и
# выглядит это как «панель повисла».
PAGE_SLICE_PER_PAGE_MAX = 500


def page_slice(page: int = 1, per_page: int = PAGE_SLICE_PER_PAGE,
               total: int = None) -> dict:
    """Границы страницы: `{'page', 'per_page', 'offset', 'limit', 'pages'}`.

    Args:
        page: номер с единицы; меньше или не число — первая.
        per_page: строк на странице; подрезается `PAGE_SLICE_PER_PAGE_MAX`.
        total: сколько строк всего. Известно — номер подрезается последней
            страницей и считается `pages`; `None` — считать нечем, и `pages`
            приходит нулём как «не знаем».

    ⚠⚠ `total` передавайте, если он известен, и считайте его **до** выборки
    строк. Без него номер не подрезается, и запрос `?page=9999` берёт строки по
    смещению, за которым ничего нет: ответ приходит с подрезанным номером («47
    из 47») и пустым списком. Выглядит это как «последняя страница пуста», а не
    как выход за край — поймано тестом ровно так.
    """
    per_page = _whole(per_page, PAGE_SLICE_PER_PAGE)
    per_page = min(max(1, per_page), PAGE_SLICE_PER_PAGE_MAX)
    page = max(1, _whole(page, 1))

    pages = 0
    if total is not None:
        pages = page_count(total, per_page)
        # ⚠ Подрезаем, а не отвергаем (см. шапку): список мог ужаться между
        # двумя нажатиями, и это не повод показывать пустой экран.
        page = min(page, pages)

    return {'page': page, 'per_page': per_page, 'pages': pages,
            'offset': (page - 1) * per_page, 'limit': per_page}


def page_count(total: int, per_page: int = PAGE_SLICE_PER_PAGE) -> int:
    """Сколько страниц у списка; пустой список — одна.

    ⚠ Деление с округлением вверх без `math.ceil`: тот переводит в float, и на
    больших списках (миллионы строк) последняя страница терялась бы на
    погрешности. `-(-a // b)` считает целыми и точен всегда.
    """
    per_page = max(1, _whole(per_page, PAGE_SLICE_PER_PAGE))

    return max(1, -(-max(0, _whole(total, 0)) // per_page))


def page_answer(rows: list, total: int, page: int = 1,
                per_page: int = PAGE_SLICE_PER_PAGE, **extra) -> dict:
    """Конверт страницы — тот, что ждёт общий пейджер панели.

    Args:
        rows: строки этой страницы.
        total: сколько строк всего (без учёта страницы).
        page, per_page: что просили.
        extra: что добавить к ответу — счётчики, фильтры, что угодно своё.

    Returns:
        `{'rows', 'total', 'page', 'pages', 'per_page', 'shown', **extra}`.

    ⚠ `shown` — длина `rows`, а не `per_page`: на последней странице их меньше,
    и подпись «показано 50 из 137» на семи строках была бы ложью.
    """
    bounds = page_slice(page, per_page, total)

    return {'rows': list(rows or []), 'total': max(0, _whole(total, 0)),
            'page': bounds['page'], 'pages': bounds['pages'],
            'per_page': bounds['per_page'], 'shown': len(rows or []),
            **extra}


# ── детали реализации ──────────────────────────────────────────────────────

def _whole(value, default: int) -> int:
    """Целое из чего угодно; не вышло — умолчание.

    ⚠ Номер страницы приезжает из адресной строки, где бывает и пусто, и
    `abc`, и `1.5`. Падать на этом нельзя: это не ошибка сервера, а опечатка
    в ссылке, и ответом должна быть первая страница.
    """
    try:
        return int(value)
    except (TypeError, ValueError):
        return default
