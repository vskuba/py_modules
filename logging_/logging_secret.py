"""Вырезание секретов из текста, который уходит в журнал.

Одни правила на всех, кто пишет наружу читаемый текст: запрос к базе
(`mysql_/mysql_log.py`), тело ответа чужого сайта, содержимое настроек. Правила
здесь **одни**, потому что вторая копия расходится с первой в первый же день,
когда список пополняют, — и расходится молча: журнал выглядит вычищенным.

## Что считается секретом

Две приметы, и обе по содержанию, а не по происхождению:

| Примета | Пример |
|---------|--------|
| ключ JSON из списка | `{"api_password": "1234"}` → `{"api_password": "•••"}` |
| пароль в строке подключения | `socks5://user:pass@host` → `socks5://user:•••@host` |

⚠ **Заменяем значение, а не строку целиком.** Вычеркнутая строка не говорит
ничего; строка с `•••` на месте пароля показывает и структуру, и место, где
секрет был, — по ней видно, что именно вырезали.

⚠ **Метка — три точки, а не звёздочки.** Звёздочки встречаются в самих
значениях, и `***` в журнале читалось бы как часть данных.

## Чего здесь нет

Угадывания «похоже на токен». Строка из сорока знаков может быть и ключом, и
идентификатором сообщения; вырезав её, мы потеряли бы ровно то, ради чего журнал
читают. Секрет опознаётся **по имени рядом с ним**, и список имён ведётся руками.
"""

import re

# Чем заменяем секрет.
LOGGING_SECRET_MARK = '•••'

# Ключи, значение которых секретно. Сравнение вхождением, поэтому
# `companion_password` и `api_password` подходят оба.
LOGGING_SECRET_KEYS = ('password', 'passwd', 'secret', 'token', 'api_key',
                       'apikey', 'private_key', 'cookie')

# Пара «ключ: значение» в JSON. ⚠ Кавычки бывают экранированными — когда сам JSON
# лежит строкой внутри другого JSON, — отсюда `\\?` в трёх местах.
_JSON_PAIR = re.compile(
    r'(\\?"[^"\\]*(?:' + '|'.join(LOGGING_SECRET_KEYS) + r')[^"\\]*\\?"\s*:\s*\\?")'
    r'([^"\\]+)(\\?")', re.IGNORECASE)

# Пароль в строке подключения: `scheme://user:pass@host`.
_URL_AUTH = re.compile(r'(://[^\s/@:]+:)([^\s/@]+)(@)')


def logging_secret_clean(text: str) -> str:
    """Текст без секретов: пары JSON и пароль строки подключения заменены меткой.

    Args:
        text: любой текст, уходящий в журнал.

    Returns:
        str: он же с вырезанными значениями. Не-строка возвращается как есть:
        звать это на числе или `None` — законно у вызывающего, который не знает
        заранее, что ему дали.
    """
    if not isinstance(text, str) or not text:
        return text

    text = _JSON_PAIR.sub(lambda m: m.group(1) + LOGGING_SECRET_MARK + m.group(3), text)

    return _URL_AUTH.sub(lambda m: m.group(1) + LOGGING_SECRET_MARK + m.group(3), text)
