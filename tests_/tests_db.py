"""База в сюите: откуда её звать и как не утащить её в закрытый цикл событий.

Две вещи, которые нужны каждой сюите, ходящей в настоящую базу, и которые у всех
получались по-своему: адрес базы, годный с хоста, и уборка после теста.

## ⚠⚠ Адрес: имя контейнера с хоста не резолвится

`MYSQL_HOST` в `.env` — имя в сети compose (`dating_mysql`), и внутри контейнера
оно верное. Сюита же идёт с хоста, а там этого имени нет; наружу база выходит
опубликованным портом.

⚠ Правится **до всякого импорта** из проекта: слой читает адрес на уровне модуля,
то есть при первом же импорте чего угодно. Поправь позже — поправишь уже
прочитанное.

⚠ Проверкой, а не безусловно: в контейнере (если сюиту однажды запустят там) имя
резолвится, и подменять его нечем и незачем.

## ⚠⚠ Одного `os.environ` мало — адрес закрепляется и на модуле

`config.config` накатывает `.env.local` с `override=True`, то есть **позже**
возвращает в окружение то, что мы только что поправили. А `mysql_.mysql_` читает
адрес один раз, на импорте. Порядок выходит такой, что правка окружения живёт до
первого обращения к конфигу и молча отменяется.

Поэтому адрес ставится дважды: в окружение (для всего, что прочитает конфиг
позже) и прямо на уже импортированный модуль базы. Поймано в проекте, где
`.env.local` есть; там, где его нет, второй шаг просто ничего не меняет.

## ⚠⚠ `.env` читается с приоритетом над окружением

Контейнеру конфиг передаёт compose, а сюите на хосте его не передаёт никто —
доменным модулям, которые тесты импортируют напрямую, нужны то же имя базы и тот
же пароль, что видит панель. Случайное окружение процесса (чужая
`MYSQL_DATABASE`) молча увело бы тесты не в ту базу.

## ⚠⚠ Уборка: сперва задачи, потом пул, и порядок не переставить

Пул привязан к циклу событий, а цикл у каждого теста свой: первый тест, позвавший
базу, создаёт пул на своём цикле, второй получает соединения от цикла, которого
уже нет, — и падает «Event loop is closed» на ровном месте.

А закрывать пул, не погасив фоновые задачи, нельзя: ручки заводят работу намеренно
и не ждут её — в этом весь смысл. Брошенная задача держит соединение, закрытие
пула ждёт, пока его вернут, и сюита встаёт намертво **без единого сообщения**.
"""

import asyncio
import os
import socket

# Куда ходить, когда имя из `.env` с хоста не резолвится. Локальная петля и
# опубликованный наружу порт — то, как compose выставляет базу на хост.
TESTS_DB_LOCAL_HOST = '127.0.0.1'

# Имя переменной, в которой лежит опубликованный порт. ⚠ Не сам порт: он у
# каждой установки свой, чтобы две базы на одной машине не сталкивались.
TESTS_DB_PORT_ENV = 'MYSQL_PORT_HOST'


def tests_db_reachable(default_port: str = '3306') -> bool:
    """Поправить адрес базы, если имя из `.env` отсюда не резолвится.

    Args:
        default_port: порт, если `MYSQL_PORT_HOST` не задан.

    Returns:
        `True` — адрес подменён (сюита идёт с хоста); `False` — имя резолвится,
        трогать нечего.

    ⚠ Зовётся **первой строкой `conftest.py`**, до импортов из проекта: иначе
    адрес уже прочитан на уровне модуля и правка опоздала.
    """
    tests_db_env_load()

    host = os.getenv('MYSQL_HOST', 'mysql')
    try:
        socket.getaddrinfo(host, None)
    except socket.gaierror:
        pass
    else:
        return False

    port = os.getenv(TESTS_DB_PORT_ENV, default_port)
    os.environ['MYSQL_HOST'] = TESTS_DB_LOCAL_HOST
    os.environ['MYSQL_PORT'] = port
    tests_db_pin(TESTS_DB_LOCAL_HOST, port)

    return True


def tests_db_pin(host: str, port: str) -> None:
    """Закрепить адрес **на самом модуле базы**, а не только в окружении.

    ⚠⚠ Без этого правка отменяется молча: `config.config` накатывает `.env.local`
    с `override=True` уже **после** нас, а `mysql_.mysql_` читает адрес один раз,
    на импорте. Поймано в проекте, где `.env.local` есть; там, где его нет,
    второй шаг просто ничего не меняет.

    Модуль ещё не импортирован — не делаем ничего: он прочитает уже поправленное
    окружение сам.
    """
    import sys

    module = sys.modules.get('mysql_.mysql_')
    if module is None:
        return

    module.host = host
    module.port = int(port)


def tests_db_env_load() -> None:
    """Прочитать `.env` установки **поверх** окружения процесса.

    ⚠ Именно поверх: случайная `MYSQL_DATABASE` в окружении молча увела бы тесты
    не в ту базу, и красным стало бы не то, что сломалось.

    Нет `python-dotenv` — тихо ничего: сюита, которой он не нужен, не обязана его
    ставить.
    """
    try:
        from dotenv import load_dotenv
    except ImportError:
        return

    load_dotenv(override=True)


async def tests_db_after() -> None:
    """Уборка после теста: погасить фоновые задачи и закрыть пул.

    ⚠⚠ Порядок не переставить — см. ⚠⚠ в заголовке модуля.

    Ставится фикстурой с `autouse=True`:

    ```python
    @pytest.fixture(autouse=True)
    async def db_pool():
        yield
        await tests_db_after()
    ```

    Цена — новое соединение на тест; база локальная, это доли миллисекунды.
    Тестов, которые её вовсе не трогают, это не касается: гасить и закрывать
    нечего.
    """
    from mysql_.mysql_ import mysql_pool_close

    await tests_db_tasks_stop()
    await mysql_pool_close()


async def tests_db_tasks_stop() -> None:
    """Отменить всё, что тест оставил работать в фоне, и дождаться конца.

    ⚠ Ждать после отмены **обязательно**: отмена доходит до задачи только на
    следующем шаге цикла, и без ожидания она успевает пожаловаться уже после
    того, как тест прошёл, — то есть красит собой следующий.
    """
    mine = asyncio.current_task()
    tasks = [task for task in asyncio.all_tasks()
             if task is not mine and not task.done()]

    for task in tasks:
        task.cancel()

    if tasks:
        await asyncio.gather(*tasks, return_exceptions=True)
