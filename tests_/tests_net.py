"""Сторож сети в сюите: наружу своей установки не ходить.

Тест, которому нужен живой сосед, проверяет не нас: он краснеет от чужого
перезапуска, от занятого пула вкладок, от переименованного сайта — и молчит про
то, ради чего написан. Тест, ходящий на живой сторонний сайт, вдобавок **делает**
там что-то: занимает вкладку, входит под учёткой, шлёт сообщение живому человеку.

Запретить это обещанием нельзя: заглушку забывают, а забытая заглушка **не
видна** — тест зеленеет, просто медленнее. Поэтому сторож стоит на сокете и
падает на попытке уйти на чужой адрес, называя тест и адрес.

## ⚠⚠ Этот сторож не отменяет `http_/http_mock.py`, и наоборот

Они ловят разное, и нужны оба:

| | что видит | чего не видит |
|---|---|---|
| сокетный (здесь) | **любое** соединение: база, Redis, чужой порт | ставится на тест и снимается с ним |
| `http_mock_guard` | только HTTP, зато **весь прогон** | не-HTTP соединения |

Сокетный ставится `monkeypatch`'ем на каждый тест — а часть работы уходит в
фоновые задачи, которых тест не ждёт. Задача доживает до следующего теста или до
конца прогона, когда сторожа уже нет, и спокойно идёт наружу. В журнале запросов
это видно поимённо: четыре настоящих входа на живой сайт за один прогон сюиты.

Отсюда правило: сокетный ловит «не-HTTP наружу» на самом тесте, `http_mock_guard`
— «HTTP наружу» на всём прогоне. Снимешь один — вторая половина перестанет
проверяться молча.
"""

import socket

# Порты своей установки, куда ходить можно всегда. MySQL (в контейнере и
# опубликованный наружу) и Redis: база настоящая намеренно — подделка проверяла
# бы подделку.
TESTS_NET_PORTS = (3306, 6379)

# Петля: только с ней разрешаются порты из `pairs`. ⚠ Имя контейнера сюда не
# входит — с хоста оно и не резолвится, а из контейнера сюиту не гоняют.
TESTS_NET_LOOPBACK = ('127.0.0.1', 'localhost', '::1')


def tests_net_allowed(address, ports=(), pairs=()) -> bool:
    """Свой ли это адрес. Всё, что не своё, — запрещено.

    Args:
        address: то, что пришло в `socket.connect`.
        ports: порты службы, разрешённые **на любом хосте** — база и Redis.
            Хост у них непредсказуем: compose раздаёт контейнерам адреса сам.
        pairs: пары `(хост, порт)`, разрешённые точно. Сюда идёт панель.

    ⚠⚠ Порт и пара — разные разрешения, и слить их нельзя. «Порт на любом хосте»
    для панели означал бы, что чужая машина на том же номере порта считается
    своей; «только петля» для базы не сработало бы вовсе — у неё адрес из сети
    compose. Проверено обратным: сторож с одним общим списком пропускал чужой
    хост на порту панели.

    ⚠ Не-кортеж пропускается: юникс-сокеты и прочее не сетевое — наружу по ним
    не уйти, а падать на них значит падать на внутренней механике питона.
    """
    if not isinstance(address, tuple) or len(address) < 2:
        return True

    host, port = str(address[0]), int(address[1] or 0)

    if port in TESTS_NET_PORTS or port in tuple(ports):
        return True

    return (host, port) in tuple(pairs)


def tests_net_guard(monkeypatch, what: str = '', ports=(), pairs=(),
                     hint: str = '') -> None:
    """Запретить тесту соединения наружу. Зовётся из фикстуры с `autouse=True`.

    Args:
        monkeypatch: фикстура pytest — ею подмена снимается вместе с тестом.
        what: имя теста для текста отказа (`request.node.name`).
        ports: порты службы, разрешённые на любом хосте, сверх умолчания.
        pairs: пары `(хост, порт)` — сюда идёт панель.
        hint: чем пользоваться вместо живого вызова — имена заглушек проекта.

    ⚠ Сторож живёт в `conftest`, а не отдельным тестом, потому что нарушение
    здесь **невидимо**: забытая заглушка не красит тест, он проходит — только
    идёт к чужой системе и делает там работу.
    """
    real_connect = socket.socket.connect
    real_connect_ex = socket.socket.connect_ex

    def check(address) -> None:
        if tests_net_allowed(address, ports, pairs):
            return

        raise AssertionError(
            f'тест «{what or "?"}» полез наружу: {address}. '
            + (hint or 'Внешние вызовы обязаны идти через заглушку.'))

    def connect(self, address):
        check(address)

        return real_connect(self, address)

    def connect_ex(self, address):
        check(address)

        return real_connect_ex(self, address)

    monkeypatch.setattr(socket.socket, 'connect', connect)
    monkeypatch.setattr(socket.socket, 'connect_ex', connect_ex)
