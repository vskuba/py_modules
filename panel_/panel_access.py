"""Договор доступа: что проект обязан уметь ответить, чтобы скелет панели работал.

Скелет не знает ни одного права по имени и не знает, где проект держит роли.
Он знает ровно три вопроса и задаёт их через этот интерфейс:

1. какие права вообще есть на установке;
2. какие права у этой роли;
3. какие поля сущности эта роль вправе читать и писать.

## ⚠⚠ Почему интерфейс, а не настройка словарём

Каталог прав — предметное знание: у одного проекта это `workflow:*` и
`agent:*`, у другого `profile:*` и `mail:*`. В общий слой оно не уезжает ни при
каких условиях (`tool_rules.md`, §1) — модуль перестал бы быть переносимым.

Но и обратное неверно: нельзя оставлять каждому проекту свою проверку прав, свой
`AuthChecker` и свою политику полей — это ровно та копия, из-за которой у одного
проекта права есть, а у двух других `is_admin` и больше ничего.

Интерфейс разводит это по месту: **механизм здесь, каталог там**. Где проект
держит раскладку — в таблице `role`, в словаре в коде, в файле — его дело и его
логика. Скелету достаточно, что на три вопроса отвечают.

## ⚠ Ответы должны быть дешёвыми

`permissions_of` зовётся **на каждый запрос**, а страница опрашивает ручки
пачками. Реализация, ходящая за этим в базу, добавит запрос к каждому вызову:
раскладку ролей держат в памяти и обновляют по своему поводу, а не на лету.

Поэтому методы синхронные: асинхронная подпись приглашала бы сходить в базу
прямо здесь.

## Подключение

```python
class OurAccess(PanelAccess):
    def permissions_all(self): return frozenset(Permission)
    def permissions_of(self, role): return ROLE_PERMISSIONS.get(role, DEFAULT)

panel_access_use(OurAccess())
```

Не подключили — скелет работает в режиме «права не заведены»: полный набор у
всех. ⚠ Это осознанное умолчание, а не дыра: панель без заведённого каталога
прав ведёт себя как панель без прав вовсе, то есть как до их появления. Дыра
была бы в обратном — пустой набор запер бы администратора снаружи.
"""

from abc import ABC, abstractmethod

# Метка «все поля» в политике полей. Отдельное значение, а не полный набор имён:
# список полей сущности меняется вместе со схемой, и «все» обязано значить «все
# нынешние», а не «те, что перечислили однажды».
PANEL_ACCESS_ALL_FIELDS = '*'

# Ключ роли по умолчанию в политике полей: правило для **любой** роли, которой не
# прописали своего. Роли заводятся на ходу, и политика, знающая только их имена,
# молча пропускала бы новую роль мимо себя.
PANEL_ACCESS_ANY_ROLE = '*'


class PanelAccess(ABC):
    """Договор доступа установки. Реализуется проектом, зовётся скелетом."""

    @abstractmethod
    def permissions_all(self) -> frozenset:
        """Весь каталог прав установки.

        По нему же определяется полнота роли: роль, у которой набор совпал с
        этим, полноправна.
        """

    @abstractmethod
    def permissions_of(self, role: str) -> frozenset:
        """Права роли. Откуда они берутся — дело проекта.

        ⚠ Зовётся на каждый запрос: см. «Ответы должны быть дешёвыми» в шапке.

        ⚠ Незнакомая роль — не ошибка, а обычный исход: роль могли завести в
        таблице и не прописать ей прав. Отвечать на такую надо **наименьшим**
        набором, а не полным.
        """

    def is_full(self, role: str) -> bool:
        """Полноправна ли роль — `admin` и служебные вроде `qa`.

        ⚠⚠ Сверяется **набор прав**, а не имя роли. Проверки вида
        `role == 'admin'` отсекали любую другую полноправную роль: учётка QA
        получала 403, имея на бумаге все права.
        """
        return self.permissions_of(role) == self.permissions_all()

    def roles_all(self):
        """Какие роли можно назначить человеку. `None` — любая непустая.

        `None` отвечает проект, у которого роли заводятся на ходу: закрытый
        список там означал бы, что роль, только что созданную в панели, нельзя
        никому выдать.

        ⚠ Закрытый список — защита от опечатки: роль `admn` завела бы учётку,
        которая не может ничего, а выглядела бы рабочей. Отказываясь от него,
        проект берёт эту проверку на себя.
        """
        return None

    def role_admin(self) -> str:
        """Как зовётся полноправная роль. Её получает первый пользователь."""
        return 'admin'

    def role_operator(self) -> str:
        """Как зовётся обычная роль. Её получает посеянный оператор."""
        return 'operator'

    def fields_allowed(self, entity: str, action: str, role: str):
        """Какие поля сущности роль вправе `read` или `write`.

        Returns:
            `PANEL_ACCESS_ALL_FIELDS` либо множество имён полей.

        Умолчание — все поля: политика полей нужна не каждому проекту, и
        отсутствие политики значит «ограничений нет», а не «ничего нельзя».
        """
        return PANEL_ACCESS_ALL_FIELDS

    def fields_filter(self, entity: str, action: str, role: str,
                      data: dict) -> dict:
        """Оставить в присланном только то, что роли писать можно.

        ⚠ Лишнее поле **отбрасывается молча**, а не отвечает отказом: форма шлёт
        себя целиком, и человек, которому поле показали серым, не виноват, что
        оно уехало. Отказ на каждое такое поле сделал бы страницу неработающей.
        """
        allowed = self.fields_allowed(entity, action, role)
        if allowed == PANEL_ACCESS_ALL_FIELDS:
            return dict(data)

        return {key: value for key, value in data.items() if key in allowed}


class PanelAccessOpen(PanelAccess):
    """Доступ «каталог прав не заведён»: всё можно всем.

    Стоит до `panel_access_use`. ⚠ Это умолчание — не дыра: панель без
    заведённого каталога ведёт себя как панель без прав вовсе, то есть как до их
    появления. Дырой был бы обратный выбор — пустой набор запер бы
    администратора снаружи собственной установки.
    """

    def permissions_all(self) -> frozenset:
        return frozenset()

    def permissions_of(self, role: str) -> frozenset:
        return frozenset()

    def is_full(self, role: str) -> bool:
        return True


def panel_access_use(access: PanelAccess) -> None:
    """Подключить договор доступа установки. Зовётся один раз, на старте.

    Args:
        access: реализация проекта.

    Raises:
        TypeError: подсунули не реализацию договора. Проверка нужна: ошибка
            здесь означала бы, что права не проверяются вовсе, а выглядело бы
            это как работающая панель.
    """
    global _access

    if not isinstance(access, PanelAccess):
        raise TypeError('доступ обязан быть реализацией PanelAccess, '
                        f'а не {type(access).__name__}')

    _access = access


def panel_access() -> PanelAccess:
    """Договор доступа установки. До подключения — «права не заведены»."""
    return _access


# ── Приватное ────────────────────────────────────────────────────────────────

# Договор установки. Один на процесс: права — свойство установки, а не запроса.
_access: PanelAccess = PanelAccessOpen()
