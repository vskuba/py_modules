"""Раздача статики панели: свои файлы плюс общие, одним путём `/static`.

Часть статики у панелей одна и та же — всплывашка уведомления, модальное окно.
Эти файлы лежали копиями в каждом проекте: правку приходилось носить руками, и
носили её не всегда.

## ⚠⚠ Почему поиск по двум каталогам, а не второй путь `/static/shared`

Второй путь означал бы правку каждой страницы, которая эти файлы подключает — а
их десятки (`notification.js` зовут 35 страниц в одном только проекте). Правка
ради правки, с риском пропустить страницу и получить 404 на живой панели.

Поиск по двум каталогам не трогает ни одной страницы: `/static/js/modal.js`
отвечает как отвечал, просто файл теперь находится в слое.

## ⚠ Порядок каталогов — договор, а не деталь

Свой каталог проекта идёт **первым**. Значит проект, положивший у себя файл с тем
же именем, перекрывает общий — и это единственный способ отойти от общего вида,
не ломая остальных. Переставь порядок, и такая правка молча перестала бы
действовать.

## ⚠⚠ `no-cache` обязателен, и это не про «не кэшировать»

Starlette отдаёт `ETag` и `Last-Modified`, но **не** `Cache-Control` — а без него
браузер решает сам и обычно кэширует эвристически, по возрасту файла. Для панели
это ломается на первой же правке: страница грузит новый HTML со старым модулем и
падает с «не экспортирует timeFull», хотя на сервере экспорт есть.

Больнее всего с ES-модулями: их браузер держит в памяти вкладки, так что обычное
обновление страницы не помогает — нужно очищать кэш руками.

`no-cache` значит «перепроверить перед использованием». Файл остаётся в кэше, но
браузер спрашивает `ETag` и почти всегда получает 304 без тела: расход — один
короткий запрос, зато панель никогда не показывает вчерашний код.

⚠ Цена приемлема, потому что панель внутренняя: десятки файлов, единицы
пользователей. Публичному сайту так делать не следует — там статику версионируют
в имени файла и кэшируют навсегда.
"""

import os

from starlette.staticfiles import StaticFiles

# Где лежит общая статика слоя. Рядом с модулем: `py_modules/panel_/static/`.
PANEL_STATIC_SHARED = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                   'static')


class PanelStatic(StaticFiles):
    """Статика панели: свой каталог, затем общий, с обязательной перепроверкой.

    Заводится не напрямую, а через `panel_static_files`.
    """

    def __init__(self, *, directory=None, shared: str = '', no_cache: bool = True,
                 **kw):
        self._shared = shared or PANEL_STATIC_SHARED
        self._no_cache = no_cache
        super().__init__(directory=directory, **kw)

    def get_directories(self, directory=None, packages=None) -> list:
        """Где искать файл: сперва у проекта, потом в общем — см. ⚠ в шапке."""
        own = super().get_directories(directory, packages)

        return [*own, self._shared] if os.path.isdir(self._shared) else own

    def file_response(self, *args, **kw):
        response = super().file_response(*args, **kw)
        if self._no_cache:
            response.headers['Cache-Control'] = 'no-cache'

        return response


def panel_static_files(directory, shared: str = '',
                       no_cache: bool = True, **kw) -> PanelStatic:
    """Раздача `/static` панели: `app.mount('/static', panel_static_files(path))`.

    Args:
        directory: каталог статики проекта — он ищется первым.
        shared: общий каталог; пусто — тот, что лежит в слое.
        no_cache: слать ли `Cache-Control: no-cache`. ⚠ Выключать только там,
            где статика версионируется в имени файла, — см. ⚠⚠ в шапке.

    ⚠ Общего каталога может не быть на диске (кто-то выкачал проект без
    submodule) — тогда раздача просто работает одним своим каталогом, а не
    падает на старте: панель без общей всплывашки лучше, чем панель, которая не
    поднялась.
    """
    return PanelStatic(directory=directory, shared=shared, no_cache=no_cache, **kw)
