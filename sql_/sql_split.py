"""
Файл SQL на отдельные команды: по `;` вне строк, имён и комментариев.

Казалось бы, `sql.split(';')`. Так и пишут, и работает это ровно до первого
файла, написанного рукой: точка с запятой живёт внутри значений (в промптах их
десятки), внутри имён в обратных кавычках и внутри шапки файла, которой человек
объясняет, зачем миграция нужна. Наивное деление рвёт команду пополам, и
половина уезжает в базу отдельным мусорным запросом.

## ⚠⚠ Разбирать надо и комментарии, а не только кавычки

Копия этой функции в слое кавычки понимала, а комментарии — нет: «seed-файлы
делает выгрузка, а не рука, и `--`-комментария с точкой с запятой в них не
бывает». Для выгрузки это правда. Для миграций — нет, и цена видна числом: из
232 файлов миграций соседнего проекта **136** разбирались неверно. Шапка
склеивалась с первой командой, а у начальной схемы расходился и счёт — 108
команд против 125.

Поэтому разбор здесь один и полный: он годится и машинному дампу, и файлу,
написанному рукой. Обратное неверно, и именно это разночтение развело две копии.

## ⚠ Что считается границей

- `'`, `"` и `` ` `` открывают кусок, внутри которого `;` — текст, а не
  разделитель. Обратные кавычки тоже: имя столбца с точкой с запятой возможно,
  и в нём разбор обязан молчать.
- `\\` внутри строки съедает следующий символ парой — иначе `\\'` закрыл бы
  строку не там, где она закрыта, и остаток файла разобрался бы наизнанку.
- `--` и `#` до конца строки **выбрасываются**: комментарий это не команда, и
  отдавать его вызывающему значило бы предложить его выполнить.
"""

# Чем открывается кусок, внутри которого `;` перестаёт быть разделителем.
# Обратная кавычка здесь не для красоты — это имя столбца, и точка с запятой
# внутри него возможна.
SQL_SPLIT_QUOTES = ("'", '"', '`')


def sql_split_statements(sql: str) -> list[str]:
    """
    Разбить текст SQL на отдельные команды.

    Args:
        sql: содержимое файла — дампа, миграции, разового скрипта.

    Returns:
        Команды без завершающей `;`, пустые отброшены. Комментарии выброшены:
        команда, состоящая из одной шапки, не возвращается вовсе.

    ⚠ Это разбор **текста**, а не разбор SQL: здесь нет ни грамматики, ни
    понимания команд. Задача ровно одна — найти те `;`, которые вправду
    разделители. Полноценный парсер стоил бы дороже задачи и вместе с тем
    сломался бы на первом же диалектном расширении.
    """
    statements, buf = [], []
    quote = None
    i = 0
    text = str(sql or '')

    while i < len(text):
        char = text[i]

        if quote:
            buf.append(char)
            # Экранированный символ берём парой: одиночный `\'` иначе закрыл бы
            # строку и увёл разбор в мусор до конца файла.
            if char == '\\' and i + 1 < len(text):
                buf.append(text[i + 1])
                i += 2
                continue
            if char == quote:
                quote = None
            i += 1
            continue

        if char in SQL_SPLIT_QUOTES:
            quote = char
            buf.append(char)
            i += 1
            continue

        # Комментарий до конца строки. Внутри него `;` — текст шапки, а не
        # разделитель; сам комментарий в команду не попадает.
        if text.startswith('--', i) or char == '#':
            end = text.find('\n', i)
            i = len(text) if end < 0 else end
            continue

        if char == ';':
            statements.append(''.join(buf).strip())
            buf = []
            i += 1
            continue

        buf.append(char)
        i += 1

    tail = ''.join(buf).strip()
    if tail:
        statements.append(tail)

    return [one for one in statements if one]


def sql_split_masked(sql: str) -> str:
    """
    Текст SQL, где содержимое строк и комментариев сбито в `X`, а строки целы.

    Нужен тому, кто ищет в SQL **знаки**, а не команды: подмену буквы в
    ключевом слове, неразрывный пробел, тире вместо минуса. Снаружи остаётся
    только синтаксис — имена, ключевые слова, числа, — и любая находка в нём
    настоящая.

    Args:
        sql: содержимое файла — миграции, дампа, разового скрипта.

    Returns:
        Текст той же длины в строках и в символах: каждый знак внутри кавычек
        и комментариев заменён на `X`, переводы строк на месте. Номер строки в
        ответе совпадает с номером строки в исходнике.

    ⚠⚠ Кавычки, слэши и комментарии разбираются ОДНИМ проходом, и порядок
    здесь не вопрос вкуса. Срезать комментарии раньше кавычек нельзя —
    апостроф в прозе шапки (`healthcheck'а`) открыл бы литерал и погасил
    пол-файла; гасить кавычки раньше комментариев нельзя — `--` внутри текста
    промпта оторвал бы литералу хвост. Оба порядка уже были испробованы на
    каталоге миграций и дали 677 и 64 ложные находки соответственно.

    ⚠ Это разбор текста, а не SQL: грамматики здесь нет, как и у соседа по
    файлу. Задача ровно одна — отделить данные от синтаксиса.
    """
    text = str(sql or '')
    out = []
    quote = None
    i = 0

    while i < len(text):
        char = text[i]

        if quote:
            # ⚠ Экранированный знак берём парой: одиночный `\'` иначе закрыл бы
            # строку и увёл разбор в мусор до конца файла.
            if char == '\\' and i + 1 < len(text):
                out.append('X')
                out.append('\n' if text[i + 1] == '\n' else 'X')
                i += 2
                continue
            if char == quote:
                quote = None
                out.append(char)
            else:
                out.append('\n' if char == '\n' else 'X')
            i += 1
            continue

        if char in SQL_SPLIT_QUOTES:
            quote = char
            out.append(char)
            i += 1
            continue

        if text.startswith('--', i) or char == '#':
            end = text.find('\n', i)
            end = len(text) if end < 0 else end
            out.append('X' * (end - i))
            i = end
            continue

        out.append(char)
        i += 1

    return ''.join(out)
