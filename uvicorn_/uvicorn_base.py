from config.config import config_get

# Под каким URI проект виден снаружи. Пусто — в корне домена.
# Слэш на конце убираем: в шаблонах пишется `{{ base }}/static/...`, и вторая
# косая дала бы `//static`, который браузер считает адресом другого хоста.
UVICORN_BASE_PATH = '/' + str(config_get('BASE_PATH', '')).strip().strip('/') \
    if str(config_get('BASE_PATH', '')).strip().strip('/') else ''


def uvicorn_base_path() -> str:
    """Базовый путь для шаблонов. Обычно пусто; если задан — без слэша на конце."""
    return UVICORN_BASE_PATH
