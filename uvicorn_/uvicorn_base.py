"""Базовый путь: под каким URI панель видна снаружи.

Проекты на общем сервере регулярно делят один домен, поделённый по пути
(`/dating`, `/persona`), а потом получают своё имя и переезжают в корень.
Переменная заведена не про запас: разводить пути задним числом пришлось бы во
всех шаблонах разом.

## ⚠⚠ Приложение префикса не видит — его срезает прокси

Само приложение всегда работает от корня: `/api/…`, `/static/js/api.js`. Беда
только в **разметке**: браузер запрашивает то, что написано в HTML, и
`/static/...` со страницы под префиксом ушёл бы к соседу по домену, а не к нам.

Отсюда правило: **в шаблонах пути пишутся с `{{ base }}`**, а в коде — как есть.
Пустой `BASE_PATH` даёт прежние абсолютные пути, и разница исчезает.

⚠ Слэш на конце убирается: в шаблонах пишется `{{ base }}/static/...`, и вторая
косая дала бы `//static`, который браузер считает адресом другого хоста.
"""

from config.config import config_get

# Под каким URI проект виден снаружи. Пусто — в корне домена.
# Слэш на конце убираем: в шаблонах пишется `{{ base }}/static/...`, и вторая
# косая дала бы `//static`, который браузер считает адресом другого хоста.
UVICORN_BASE_PATH = '/' + str(config_get('BASE_PATH', '')).strip().strip('/') \
    if str(config_get('BASE_PATH', '')).strip().strip('/') else ''


def uvicorn_base_path() -> str:
    """Базовый путь для шаблонов. Обычно пусто; если задан — без слэша на конце."""
    return UVICORN_BASE_PATH
