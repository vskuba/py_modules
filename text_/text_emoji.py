"""Эмодзи к одному виду: починка знаков, разобранных чужим кодом неверно.

## ⚠⚠ Что чинится

Эмодзи лежат выше основной плоскости (`U+1F300`–`U+1FAFF`), и в экранированном виде их
номер занимает **пять** шестнадцатеричных цифр: `\\u1F609` — это 😉. Разборщик,
читающий ровно четыре цифры (а так устроен `\\uXXXX` в JavaScript, JSON и многих
шаблонизаторах), берёт `1F60`, а пятую цифру оставляет в тексте буквой.

Выходит пара «знак греческого расширенного плюс цифра»:

    😉  U+1F609        →  ὠ9      U+1F60 + '9'
    👍  U+1F44D        →  ὄD      U+1F44 + 'D'

Текст при этом не ломается и не подсвечивается ошибкой — он просто становится
другим. Две записи одной и той же реплики перестают совпадать, а человек видит в
переписке греческую букву.

## ⚠ Почему такое разворачивается однозначно

Первая половина искажения попадает в блок Greek Extended (`U+1F00`–`U+1FFF`) —
политонический древнегреческий. В переписке на английском, русском или украинском
он не встречается вовсе, а уж следом за ним шестнадцатеричная цифра — тем более.
Признак настолько редкий, что ложное срабатывание практически исключено.

Сужаем ещё: берём `U+1F00`–`U+1FAF`, потому что именно они дают номера
`U+1F000`–`U+1FAFF` — все блоки эмодзи и ничего сверх них. Хвост греческого
(`U+1FB0`+) развернулся бы в «символы старых ЭВМ», которых в переписке быть не может.

## ⚠ Чего здесь нет намеренно

**Раскрытия `\\uXXXX` из текста.** Соблазн велик, но текст сообщения — это то, что
человек написал: захоти он передать буквально `\\u1F609`, мы обязаны это сохранить.
Чинится разбор, а не содержание.

**Выбрасывания эмодзи.** Приведение к одному виду — это починка, а не зачистка:
😉 остаётся 😉.
"""

# Первые половины искажённых пар. Нижняя граница — начало Greek Extended, верхняя
# выбрана так, чтобы развёрнутый номер не вышел за последний блок эмодзи
# (`U+1FAFF`): всё, что выше, — уже не эмодзи, и трогать его нельзя.
TEXT_EMOJI_HEAD_FIRST = 0x1F00
TEXT_EMOJI_HEAD_LAST = 0x1FAF

# Хвост пары — та самая пятая цифра номера, оставшаяся в тексте буквой. Обе
# раскладки: номер мог быть записан и строчными (`ὠ9`), и прописными.
TEXT_EMOJI_TAIL = '0123456789abcdefABCDEF'


def text_emoji_fix(text: str) -> str:
    """Починить эмодзи, разобранные чужим кодом неверно: `ὠ9` снова 😉.

    Args:
        text: любая строка. Не строка и пустая — возвращаются как есть.

    Returns:
        str: текст с восстановленными знаками. Если чинить нечего — **тот же
        объект**, без пересборки: вызывать на каждом сообщении дёшево.

    ⚠ **Зовётся на границе**, где текст приходит снаружи: со страницы, из
    сценария, из чужого API. Внутри нашего кода звать её уже незачем — и вредно:
    привычка «на всякий случай» прячет место, где искажение возникло.

    >>> text_emoji_fix('talking? \\u1f60' + '9')
    'talking? 😉'
    >>> text_emoji_fix('ok')
    'ok'
    """
    if not isinstance(text, str) or len(text) < 2:
        return text

    # Быстрая проверка: нет ни одной головы — уходим, ничего не собирая. Так
    # выглядит подавляющее большинство сообщений.
    if not any(TEXT_EMOJI_HEAD_FIRST <= ord(ch) <= TEXT_EMOJI_HEAD_LAST
               for ch in text):
        return text

    out, i, size = [], 0, len(text)

    while i < size:
        ch = text[i]

        if TEXT_EMOJI_HEAD_FIRST <= ord(ch) <= TEXT_EMOJI_HEAD_LAST \
                and i + 1 < size and text[i + 1] in TEXT_EMOJI_TAIL:
            # Номер собирается обратно: голова — старшие цифры, хвост — младшая.
            out.append(chr(ord(ch) * 16 + int(text[i + 1], 16)))
            i += 2

            continue

        out.append(ch)
        i += 1

    return ''.join(out)


def text_emoji_same(text: str) -> str:
    """Текст, приведённый к одному виду: эмодзи — настоящими знаками.

    Одна дверь для вызывающего: сегодня за ней починка разобранных пар, завтра —
    то, что найдётся ещё. Места вызова при этом не меняются.

    Args:
        text: строка откуда угодно снаружи.

    Returns:
        str: тот же текст в каноническом виде.

    ⚠ Суррогатные половины (`U+D800`–`U+DFFF`) сюда не попадают и не чинятся:
    из `utf8mb4` и из `json` они прийти не могут — первый их не кодирует, второй
    склеивает пару сам. Появятся — им здесь и место.
    """
    return text_emoji_fix(text)
