"""Кириллица в строке: есть хоть один знак — True, нет — False.

Знак кириллицы в тексте — маркер, что строка поехала не в тот язык: ответ
просили на английском, а вернулся он, например, русским. Отличить одно от
другого иначе дёшево не получается, а сам признак — наличие буквы
кириллического блока — становится делом одной проверки.

## ⚠⚠ `[а-яА-Я]` — неверная примета, берите весь блок

Привычный `[а-яА-Я]` годится только для русского, и то не всего: в диапазон
`а-я` не входят `ё` и `Ё` (они уехали на `U+0401`/`U+0451`), вне его остаются
украинские `є і ї ґ`, белорусское `ў`, сербские `ђ ћ ј љ њ џ`. Проверка,
написанная через `а-я`, на ровном месте пропускает половину того, зачем её
писали. Здесь взят весь блок `U+0400`–`U+04FF` разом: русский, украинский,
белорусский, сербский, — и обе раскладки, и `ё` внутри.

Дополнение кириллицы (`U+0500`–`U+052F`) не взята намеренно: это исторические
зырянские и ханты-мансийские буквы, в переписке и в выводе моделей они не
бывают.

## ⚠ Марка алфавита — это не язык

Кириллица в строке не значит «русский»: тем же блоком пишут украинский,
болгарский, казахский. И наоборот: в английский текст человек может вставить
цитату или фамилию (`Толстой`) — кириллица есть, язык английский. Достаточен
ли одного знака, чтобы браковать строку, решает вызывающий.

## Чего модуль НЕ делает

**Не ищет кириллицу в именах кода.** Для этого есть
`variable_/variable_cyrillic.py`: там разбор `ast`, потому что в коде русские
комментарии — норма, и текстовый поиск по ним тонет.

**Не чинит и не вырезает.** Он отвечает «да/нет»; переписывать чужой текст —
не его дело.
"""
import re

# Признак кириллицы — весь блок U+0400–U+04FF: см. заголовок модуля, почему
# не `[а-яА-Я]`.
TEXT_CYRILLIC_RE = re.compile('[\u0400-\u04FF]')


def text_cyrillic_has(text) -> bool:
    """Есть ли в строке кириллица: хоть один знак — True.

    Args:
        text: любая строка. Не строка (`None`, `bytes`, число) — False: знак
        ищут в тексте, в байтах смотреть не на что.

    Returns:
        bool: True — кириллица есть, False — нет.

    ⚠ Это марка алфавита, а не языка: блок общий у русского, украинского,
    сербского. Когда одного знака достаточно и когда нет — в заголовке
    модуля.

    >>> text_cyrillic_has('Спорю, ты сейчас улыбнулся')
    True
    >>> text_cyrillic_has('Привіт, друзі!')
    True
    >>> text_cyrillic_has("I'm writing first because you liked me")
    False
    >>> text_cyrillic_has('42!? — ok')
    False
    >>> text_cyrillic_has('')
    False
    >>> text_cyrillic_has(None)
    False
    """
    return isinstance(text, str) and TEXT_CYRILLIC_RE.search(text) is not None
