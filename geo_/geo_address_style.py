"""Адрес одной строкой — такой, каким его пишет человек в форме заказа.

Задача выглядит как «склеить улицу, дом и квартиру», и в этом виде решается
одной строкой. Беда та же, что у почты (`email_make.md`): одна строка даёт
**однообразие**, а однообразие видно сразу. Пятьсот заказов вида
`вул. Теремська, 12, кв. 45` отличаются только цифрами и читаются как список,
сделанный скриптом.

Живые люди пишут иначе — и каждый по-своему:

```
вул. Теремська, 12, кв. 45      ← самый частый вид
Теремська 12/45
вулиця Теремська, буд. 12, кв. 45
м. Київ, вул. Теремська 12, кв 45
вул.Теремська, 12, кв.45
Теремська, 12, кв. 45
```

Модуль перебирает ровно те формы, которые встречаются живьём, и смешивает их
случайно. Что в них меняется:

| Что | Варианты |
|-----|----------|
| тип улицы | `вул.` · `вулиця` · `вул` · опущен совсем |
| запятая после улицы | есть · нет |
| слово перед домом | нет · `буд.` · `б.` |
| квартира | `кв. 45` · `кв.45` · `кв 45` · `/45` · `, 45` · `квартира 45` |
| город в начале | нет · `Київ, ` · `м. Київ, ` |
| пробел после точки | `вул. Х` · `вул.Х` |

## ⚠⚠ Доли не равномерные, и это главное

Равномерный выбор из шести форм — такой же признак генератора, как одна форма:
в живом потоке «вул. Теремська, 12, кв. 45» встречается вдесятеро чаще, чем
«Теремська 12/45». Веса в таблицах подобраны под это, и ровнять их нельзя.

## ⚠⚠ Город в строке — РЕДКО

У формы магазина есть отдельное поле «Місто», и город в адресной строке его
дублирует. Люди всё же иногда пишут — отсюда малая доля
(`GEO_ADDRESS_STYLE_CITY`), а не ноль и не треть.

## ⚠ Улицы с типом в конце не трогаются

«Андріївський узвіз», «Паркова алея» — тип там стоит после названия, и
переставлять его нельзя (`geo_osm_address_street` знает то же правило). Такие
улицы идут как есть, меняется только остальное.

## ⚠ Почему `rand` — довод, а не глобальный `random`

Разнообразие проверяют счётом: «на двухстах адресах вышло столько-то разных
форм». Такой проверке нужен повторяемый источник случайности, иначе тест то
проходит, то нет. То же правило, что в `email_` и `person_ua`.
"""

import random
import re

# Как человек пишет тип улицы. ⚠ Доли не равномерные: сокращение с точкой —
# то, что подставляет половина браузеров из автозаполнения.
GEO_ADDRESS_STYLE_KINDS = (
    ('short', 58),    # вул. Теремська
    ('none', 20),     # Теремська
    ('long', 14),     # вулиця Теремська
    ('bare', 8),      # вул Теремська
)

# Полная форма сокращения — для варианта `long`.
GEO_ADDRESS_STYLE_LONG = {
    'вул.': 'вулиця', 'просп.': 'проспект', 'пров.': 'провулок',
    'бульв.': 'бульвар', 'пл.': 'площа', 'наб.': 'набережна',
    'туп.': 'тупик',
}

# Типы, которые в украинском стоят ПОСЛЕ названия: их не переставляют.
GEO_ADDRESS_STYLE_TAIL_KINDS = ('узвіз', 'алея', 'дорога', 'шосе')

# Чем отделяют улицу от дома.
GEO_ADDRESS_STYLE_HOUSE = (
    (', ', 72),       # вул. Теремська, 12
    (' ', 28),        # вул. Теремська 12
)

# Слово перед номером дома. Пусто — обычный случай.
GEO_ADDRESS_STYLE_HOUSE_WORD = (
    ('', 86), ('буд. ', 9), ('б. ', 5),
)

# Как пишут квартиру. ⚠ `/45` и `, 45` — формы без слова: так пишут, когда
# поле одно и места мало.
GEO_ADDRESS_STYLE_FLAT = (
    (', кв. {flat}', 54),
    (', кв.{flat}', 14),
    (', кв {flat}', 11),
    ('/{flat}', 8),
    (', {flat}', 7),
    (', квартира {flat}', 4),
    (' кв. {flat}', 2),
)

# Как пишут город, когда пишут. См. шапку — это редкий случай.
GEO_ADDRESS_STYLE_CITY_FORMS = (
    ('{city}, ', 62), ('м. {city}, ', 38),
)

# Доля адресов, где город всё-таки написан в строке.
GEO_ADDRESS_STYLE_CITY = 0.12

# Доля адресов, где после сокращения забыт пробел: «вул.Теремська».
GEO_ADDRESS_STYLE_TIGHT = 0.09


def geo_address_style(street: str, house: str, flat: str = '', city: str = '',
                      rand: random.Random = None) -> str:
    """Собрать адрес одной строкой — в одной из живых форм записи.

    Args:
        street: улица в канонической форме, как её отдаёт
            `geo_osm_address_street`: «вул. Теремська».
        house: номер дома — «12», «6-В», «53/80».
        flat: номер квартиры; пусто — частный дом, квартиры не будет вовсе.
        city: город; попадёт в строку редко (см. шапку) — пусто означает «не
            писать никогда».
        rand: `random.Random` для повторяемости; `None` — обычный случай.

    Returns:
        Готовая строка для поля «Адреса 1». Пустая улица или пустой дом —
        пустая строка: собирать не из чего.

    ⚠⚠ Зовётся ОДИН раз на карточку, а результат записывается. Вызови её
    дважды на тот же дом — получишь две разные строки, и человек увидел бы в
    отчёте одно, а в магазине другое.

    ⚠ В примерах ниже seed задан, и потому вид записи предсказуем. Без него
    тот же дом даёт разные строки — в этом и смысл модуля.

    >>> geo_address_style('вул. Теремська', '12', '45', 'Київ',
    ...                   random.Random(3))
    'Київ, вул. Теремська, 12, кв.45'
    >>> geo_address_style('вул. Миру', '7', '', '', random.Random(11))
    'вул. Миру 7'
    >>> geo_address_style('вул. Теремська', '12', '45', '', random.Random(2))
    'вул Теремська 12, кв. 45'
    >>> geo_address_style('', '12', '45')
    ''
    """
    rand = rand or random
    street, house = str(street or '').strip(), str(house or '').strip()
    if not street or not house:
        return ''

    whole = _style_street(street, rand)
    whole += _pick(GEO_ADDRESS_STYLE_HOUSE, rand)
    whole += _pick(GEO_ADDRESS_STYLE_HOUSE_WORD, rand) + house

    if flat:
        # ⚠⚠ Слэш-форма («12/45») не годится дому, в номере которого слэш уже
        # есть: «53/80» — это корпусный номер, и «53/80/45» читается как
        # опечатка, а не как квартира. Таким домам достаются формы со словом.
        forms = GEO_ADDRESS_STYLE_FLAT
        if '/' in house:
            forms = tuple((one, weight) for one, weight in forms
                          if not one.startswith('/'))

        whole += _pick(forms, rand).format(flat=flat)

    if city and rand.random() < GEO_ADDRESS_STYLE_CITY:
        whole = _pick(GEO_ADDRESS_STYLE_CITY_FORMS, rand).format(city=city) \
            + whole

    return whole


# ── детали реализации ──────────────────────────────────────────────────────

def _style_street(street: str, rand: random.Random) -> str:
    """Улица в одной из форм записи: с типом, без типа, полным словом.

    ⚠ Улица, у которой тип стоит в конце («Андріївський узвіз»), отдаётся как
    есть: перестановка её портит, а отбрасывание типа превращает в фамилию.
    """
    low = street.lower()
    if any(mark in low for mark in GEO_ADDRESS_STYLE_TAIL_KINDS):
        return street

    found = re.match(r'^([а-яіїєґ]+\.)\s*(.+)$', street, re.IGNORECASE)
    if not found:
        return street

    short, name = found.group(1), found.group(2).strip()
    shape = _pick(GEO_ADDRESS_STYLE_KINDS, rand)

    if shape == 'none':
        return name
    if shape == 'long':
        return f'{GEO_ADDRESS_STYLE_LONG.get(short, short)} {name}'
    if shape == 'bare':
        return f'{short.rstrip(".")} {name}'

    # ⚠ Пропущенный пробел — не опечатка кода, а то, как печатают в спешке.
    gap = '' if rand.random() < GEO_ADDRESS_STYLE_TIGHT else ' '

    return f'{short}{gap}{name}'


def _pick(weighted, rand: random.Random):
    """Случайный элемент из `((значение, вес), …)` с учётом весов."""
    values = [value for value, _ in weighted]
    weights = [weight for _, weight in weighted]

    return rand.choices(values, weights=weights, k=1)[0]
