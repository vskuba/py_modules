"""Счётчик запросов к базе: что спрашивали, сколько это стоило и что вернулось.

## Зачем

Журнал запросов (`mysql_log_line`) отвечает на вопрос «что сейчас спросили» — и
для отладки этого хватает. На вопрос «куда уходит время базы» он не отвечает
вовсе: строк в нём тысячи в минуту, они одинаковые, и сложить их глазами нельзя.
Замерено на живом сервере: воркер писал 6832 строки в минуту, из них 6809 — эти
самые печати.

Здесь то же самое, но сложенное: строка не на прогон запроса, а на **вид**
запроса, с числами. Сколько раз спросили, сколько всего на это ушло, сколько
занял самый долгий случай и сколько строк вернулось.

## ⚠ Строка одна на отпечаток — иначе счётчик становится второй бедой

Соблазн писать строку на каждое выполнение велик, и он ложный: при шести тысячах
запросов в минуту это десять миллионов строк в сутки и удвоенная нагрузка на ту
самую базу, которую этим счётчиком и собирались чинить. Поэтому накопление идёт
**в памяти процесса**, а наружу отдаётся пачкой (`mysql_watch_drain`) — кто и
куда её denет, модуль не знает и знать не должен.

Тот же приём, что у журнала ошибок: одна строка на отпечаток, повторы в счётчик.

## Что такое «вид запроса»

Текст запроса с плейсхолдерами, каким его написали в коде: значения в нём и так
не участвуют — они едут отдельно, в `args`. Приводится к одному виду только то,
что меняется от вызова к вызову у одного и того же места кода:

* пробелы и переводы строк — запрос, собранный из склеенных строк, и он же в одну
  строку это один вид;
* длина списка в `IN (%s, %s, %s)` — число плейсхолдеров там равно числу
  элементов, и без сведения один и тот же отбор давал бы новый вид на каждый
  размер списка;
* то же для пачек в `VALUES (...), (...)`.

## ⚠ Значения хранятся от **самого долгого** случая, а не от последнего

Вопрос, ради которого счётчик заводят, звучит «почему этот запрос иногда
медленный». Отвечают на него аргументы того прогона, который и был медленным;
аргументы последнего к нему отношения не имеют. Секреты из них вырезаны
(`mysql_log_args`) — правила общие с журналом запросов, см. `docs/observability_rules.md`, §10.
"""

import hashlib
import re
import threading
import time
from datetime import datetime, timezone

from mysql_.mysql_log import mysql_log_args

# Длина текста запроса, которую храним. Длиннее — обрезается: вид запроса
# узнаётся по началу, а целиком он есть в коде.
MYSQL_WATCH_QUERY_MAX = 4000

# Длина строки аргументов. Значения бывают килобайтными (снимок переменных,
# тело страницы), и счётчику незачем становиться их хранилищем.
MYSQL_WATCH_ARGS_MAX = 2000

# Сколько разных видов запроса помним. Потолок — от утечки: вид запроса берётся
# из текста, а текст бывает собран по месту, и при неудачной сборке их станет
# сколько угодно. Переполнение молча перестаёт заводить новые виды, уже
# заведённые продолжают считаться.
MYSQL_WATCH_SHAPES_MAX = 2000


def mysql_watch_enabled() -> bool:
    """Считаем ли запросы. Выключен — `mysql_watch_note` возвращается сразу."""
    return _watch['on']


def mysql_watch_on(source: str = '') -> None:
    """Включить счётчик, назвав процесс.

    Args:
        source: чей это процесс — попадёт в каждую строку пачки. Пусто —
            останется пустым, разбираться будет вызывающий.

    ⚠ Включает **только счёт в памяти**. Куда девать накопленное, модуль не
    решает: забирает его `mysql_watch_drain`, и зовёт её тот, кто знает, куда
    писать.
    """
    _watch['on'] = True
    _watch['source'] = str(source or '')


def mysql_watch_off() -> None:
    """Выключить счётчик и забыть накопленное."""
    with _lock:
        _watch['on'] = False
        _shapes.clear()


def mysql_watch_note(query, args, ms: float, rows: int) -> None:
    """Записать один прогон запроса.

    Args:
        query: сам запрос, как он ушёл в базу.
        args: значения запроса либо `None`.
        ms: сколько занял прогон, миллисекунды.
        rows: сколько строк вернул (или затронул).

    ⚠ **Ничего не бросает и ничего не ждёт.** Это счётчик: он обязан быть дешевле
    того, что считает. Любая его неудача — молчаливая, иначе сломанный счётчик
    ронял бы запросы приложения.

    ⚠ Во время сброса (`mysql_watch_hold`) не считает ничего: сброс сам ходит в
    базу теми же запросами, и без этого счётчик считал бы собственную работу — и
    на каждом сбросе заводил бы её заново.
    """
    if not _watch['on'] or getattr(_busy, 'flag', False):
        return

    try:
        shape = mysql_watch_shape(query)
        mark = mysql_watch_fingerprint(shape)
        now = datetime.now(timezone.utc)
        ms = float(ms)
        rows = max(0, int(rows or 0))

        with _lock:
            one = _shapes.get(mark)
            if one is None:
                if len(_shapes) >= MYSQL_WATCH_SHAPES_MAX:
                    return
                one = _shapes[mark] = {
                    'fingerprint': mark, 'query': shape, 'source': _watch['source'],
                    'hits': 0, 'total_ms': 0.0, 'max_ms': 0.0,
                    'total_rows': 0, 'max_rows': 0,
                    'slow_ms': -1.0, 'slow_rows': 0, 'slow_args': '', 'slow_at': now,
                    'first_at': now, 'last_at': now,
                }

            one['hits'] += 1
            one['total_ms'] += ms
            one['total_rows'] += rows
            one['max_ms'] = max(one['max_ms'], ms)
            one['max_rows'] = max(one['max_rows'], rows)
            one['last_at'] = now

            # Значения — от самого долгого случая: он и есть предмет вопроса.
            if ms > one['slow_ms']:
                one['slow_ms'] = ms
                one['slow_rows'] = rows
                one['slow_args'] = _args_text(query, args)
                one['slow_at'] = now
    except Exception:
        # Счётчик молчит о своих бедах: жаловаться ему некуда, а ронять
        # вызывающего он не вправе.
        pass


def mysql_watch_drain() -> list[dict]:
    """Забрать накопленное и обнулить счёт.

    Returns:
        list[dict]: по строке на вид запроса — `fingerprint`, `query`, `source`,
        `hits`, `total_ms`, `max_ms`, `total_rows`, `max_rows`, `slow_ms`,
        `slow_rows`, `slow_args`, `slow_at`, `first_at`, `last_at`.

    ⚠ **Забирает, а не копирует.** Второй вызов подряд вернёт пустой список:
    накопленное отдано, и складывать его дальше должен тот, кто взял. Так
    сделано, чтобы пачка не уехала в базу дважды при двух сбросах подряд.
    """
    with _lock:
        out = list(_shapes.values())
        _shapes.clear()

    return out


def mysql_watch_hold():
    """Не считать запросы внутри блока — `with mysql_watch_hold():`.

    Нужно тому, кто сбрасывает накопленное: сброс ходит в базу обычными
    запросами, и без этого счётчик считал бы сам себя.
    """
    return _Hold()


def mysql_watch_shape(query) -> str:
    """Вид запроса: текст без того, что меняется от вызова к вызову.

    Сводятся пробелы и длина списков плейсхолдеров (шапка модуля). Значения в
    тексте не участвуют — они едут в `args` отдельно.
    """
    text = ' '.join(str(query or '').split())
    text = _IN_LIST.sub(lambda m: f'{m.group(1)} (%s)', text)
    text = _VALUES_ROWS.sub('VALUES (%s)', text)

    return text[:MYSQL_WATCH_QUERY_MAX]


def mysql_watch_fingerprint(shape: str) -> str:
    """Отпечаток вида запроса — 32 знака md5. По нему повтор находит свою строку."""
    return hashlib.md5(str(shape or '').encode('utf-8', errors='ignore')).hexdigest()


# ── Приватное ────────────────────────────────────────────────────────────────

# Состояние счётчика на процесс и замок к нему: считают из разных потоков —
# обработчик запроса, поток `rq`, фоновая задача.
_watch = {'on': False, 'source': ''}
_shapes: dict[str, dict] = {}
_lock = threading.Lock()

# «Мы внутри сброса» — свой на поток, как у журнала ошибок: сбрасывать могут
# из разных, и глобальный флаг погасил бы счёт чужому.
_busy = threading.local()

# Список плейсхолдеров после `IN`: длина его равна длине списка значений.
_IN_LIST = re.compile(r'\b(IN|NOT\s+IN)\s*\(\s*%s(?:\s*,\s*%s)+\s*\)', re.IGNORECASE)

# Пачка строк во вставке: `VALUES (%s, %s), (%s, %s), ...`.
_VALUES_ROWS = re.compile(r'\bVALUES\s*\(\s*%s(?:\s*,\s*%s)*\s*\)'
                          r'(?:\s*,\s*\(\s*%s(?:\s*,\s*%s)*\s*\))*', re.IGNORECASE)


class _Hold:
    """Тело `mysql_watch_hold`: поднимает флаг потока и опускает его обратно."""

    def __enter__(self):
        self._was = getattr(_busy, 'flag', False)
        _busy.flag = True
        return self

    def __exit__(self, *_):
        _busy.flag = self._was
        return False


def _args_text(query, args) -> str:
    """Значения запроса строкой, с вырезанными секретами и обрезанным хвостом.

    ⚠ Вырезает их `mysql_log_args` — тот же код, что чистит журнал запросов.
    Вторая копия правил разошлась бы с первой в первый же день, когда список
    секретных имён пополнят, и разошлась бы молча.
    """
    if not args:
        return ''

    try:
        safe = mysql_log_args(query, args)
    except Exception:
        safe = args

    return str(safe)[:MYSQL_WATCH_ARGS_MAX]
