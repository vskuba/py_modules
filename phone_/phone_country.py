"""Страновой номер: канон вида +380XXXXXXXXX, код оператора — одними руками,
там же и генератор живого украинского номера.

Номер читают отовсюду — подписчик из Telegram, карточка заказа, выгрузка из
таблицы, — и везде ему нужен один и тот же канон и один и тот же код оператора.
Держать разбор у каждого хозяина — значит через месяц иметь две таблицы, которые
молча разошлись. Здесь они одни: проект знает, КУДА сохранять номер, а как он
выглядит канонно — здесь. Страна пока одна, украинская; чужие номера тоже
получают канон, просто без кода.
"""
import argparse
import random

from json_.json_out import json_out

# Украинский мобильный: 12 цифр с +380, код оператора — 3-я и 4-я цифры.
PHONE_UA_COUNTRY = '380'

# Коды украинских мобильных операторов (план нумерации). Генератор берёт только
# отсюда: городские (`044` Киев, `056` Днепр) и сервисные (`0800`) номера в
# заказе на доставку выглядят чужеродно — там ждут мобильный.
PHONE_UA_OPERATORS = (
    '039', '050', '063', '066', '067', '068', '073', '075', '077', '091',
    '092', '093', '094', '095', '096', '097', '098', '099',
)


def phone_parse(raw: str) -> dict:
    """Нормализовать номер к канону и вынуть код оператора; ничего не бросает.

    Принимает что угодно: с пробелами и черточками, `+380…` и местный `0XX…` —
    всё, из чего остались цифры, станет номером. Чужой стране канон тоже
    положит (`+998…`, `+47…`), но кода украинской таблицы ей не даст.

    Args:
        raw: номер как пришёл — из контакта, из чата, из выгрузки.

    Returns:
        {'phone': '+…' канон; пусто — если из строки не осталось ни одной
        цифры, там был не номер; 'operator_code': '0XX' для украинских,
        пусто для чужих стран; 'valid': украинский ли это мобильный (ровно
        +380 и 12 цифр) — чужой номер каноничен, но не valid; сохранять ли
        такой — решает вызывающий, здесь он просто описан}.
    """
    digits = ''.join(c for c in str(raw) if c.isdigit())
    if len(digits) == 10 and digits.startswith('0'):
        digits = PHONE_UA_COUNTRY + digits[1:]   # местный вид '067…' → '38067…'
    ua = digits.startswith(PHONE_UA_COUNTRY) and len(digits) == 12
    return {'phone': f'+{digits}' if digits else '',
            'operator_code': f'0{digits[3:5]}' if ua else '',
            'valid': ua}


def phone_ua_make(rand: random.Random = None) -> str:
    """Сгенерировать живой украинский мобильный — канонный +380… с настоящим
    кодом оператора.

    Нужен там, где номер не читают у подписчика, а заводят сами: резерв
    покупателей, тестовая пачка. Форма та же, что вернул бы `phone_parse` для
    настоящего номера: 12 цифр, код из таблицы плана нумерации, семь цифр
    абонента случайные.

    ⚠ Уникальность — дело вызывающего: пространство 1,8 × 10⁸ номеров, и на
    пачке в тысячи повтор маловероятен, но возможен. Вставка с проверкой на
    дубль здесь же, а не внутри генератора.

    Args:
        rand: источник случайности; свой нужен тестам на воспроизводимость.

    Returns:
        str: номер в каноне, вида '+380671234567'.
    """
    rand = rand or random
    code = rand.choice(PHONE_UA_OPERATORS)
    tail = ''.join(str(rand.randrange(10)) for _ in range(7))

    return f'+{PHONE_UA_COUNTRY}{code[1:]}{tail}'


if __name__ == '__main__':
    p = argparse.ArgumentParser(
        description='Номер к канону и код оператора: что пришло — то и разобрано.')
    p.add_argument('phone', nargs='*', help='номера как есть: +380…, 0…, с черточками')
    p.add_argument('--make', type=int, default=0,
                   help='сгенерировать N живых украинских номеров вместо разбора')
    ns = p.parse_args()

    if ns.make:
        print(json_out([phone_ua_make() for _ in range(ns.make)]))
    else:
        print(json_out([phone_parse(raw) for raw in ns.phone]))
